"""Kotlin emitter — typed attribute extraction data classes (Kotlin 2.x).

Dependency choice
-----------------
The generated parsers take a plain ``Map<String, Any?>`` — **zero external
dependencies** (pure Kotlin stdlib). Both realistic call sites convert
cheaply:

- ``org.json``:   ``JSONObject.toMap()`` (or a 5-line manual walk)
- kotlinx:        ``JsonObject`` → primitive map via a small adapter

This keeps ``library-dynamic`` free to keep (or change) its JSON library
without regenerating, and keeps the generated code compilable with nothing
but ``kotlinc``.

Emitted files mirror the Swift emitter: ``AttrCodegenSupport.kt``,
``CommonAttributes.kt`` (shared base, emitted once), and per-component
``<Component>Attributes.kt`` diffs embedding ``common``.
"""
from __future__ import annotations

from ...core.type_mapper import TypeMapper
from .model import Attribute, AttrKind, AttrModel, Component
from .swift_emitter import _pascal, _split_words, dimension_type_name, enum_cases

PACKAGE = "com.kotlinjsonui.dynamic.generated"

HEADER = (
    "// @generated by `jui generate attr-bindings` — DO NOT EDIT BY HAND.\n"
    "// Source of truth: shared/core/attribute_definitions.json\n"
    "// Regenerate: jui generate attr-bindings --lang kotlin\n"
)

_KOTLIN_KEYWORDS = frozenset({
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun",
    "if", "in", "interface", "is", "null", "object", "package", "return",
    "super", "this", "throw", "true", "try", "typealias", "typeof", "val",
    "var", "when", "while",
})


def emit(model: AttrModel) -> dict[str, str]:
    """Return ``{relative_path: content}`` for the Kotlin output (sorted)."""
    mapper = TypeMapper()
    files: dict[str, str] = {}
    files["AttrCodegenSupport.kt"] = _support_file(model)
    files["CommonAttributes.kt"] = _component_file(model.common, model, mapper)
    for comp in model.components:
        files[f"{comp.name}Attributes.kt"] = _component_file(comp, model, mapper)
    return dict(sorted(files.items()))


# ---------------------------------------------------------------------------
# Support file
# ---------------------------------------------------------------------------

def _support_file(model: AttrModel) -> str:
    parts = [HEADER.rstrip("\n"), "", f"package {PACKAGE}", ""]
    parts.append('''\
/**
 * Static value or `@{binding}` expression for a binding-capable attribute.
 */
sealed class AttrValue<out T> {
    data class Value<T>(val value: T) : AttrValue<T>()

    /** The expression inside `@{...}` (without the wrapper). */
    data class Binding(val expression: String) : AttrValue<Nothing>()

    fun valueOrNull(): T? = when (this) {
        is Value -> value
        is Binding -> null
    }

    fun bindingExpressionOrNull(): String? = when (this) {
        is Value -> null
        is Binding -> expression
    }
}

/**
 * Warning hook — generated parsers never crash on malformed input.
 * Unknown enum values / dimension keywords are reported here and parsed
 * as null.
 */
object AttrWarnings {
    var handler: ((String) -> Unit)? = null

    fun emit(message: String) {
        handler?.invoke(message)
    }
}

/** Coercion helpers used by the generated `parse(json)` implementations. */
object AttrCoerce {
    /**
     * Canonical-name lookup with alias fallback (aliases are resolved in
     * generated code so raw / non-normalized JSON keeps working).
     */
    fun lookup(
        json: Map<String, Any?>,
        canonical: String,
        aliases: List<String> = emptyList()
    ): Any? {
        json[canonical]?.let { return it }
        for (alias in aliases) {
            json[alias]?.let { return it }
        }
        return null
    }

    /** `"@{expr}"` → `"expr"`; anything else → null. */
    fun bindingExpression(raw: Any?): String? {
        val s = raw as? String ?: return null
        if (!s.startsWith("@{") || !s.endsWith("}") || s.length <= 3) return null
        return s.substring(2, s.length - 1)
    }

    /** Binding-only attributes accept `@{fn}` (canonical) or a bare name. */
    fun bindingExprOrName(raw: Any?): String? =
        bindingExpression(raw) ?: string(raw)

    fun string(raw: Any?): String? = raw as? String

    fun number(raw: Any?): Double? = (raw as? Number)?.toDouble()

    fun boolean(raw: Any?): Boolean? = raw as? Boolean

    fun obj(raw: Any?): Map<String, Any?>? {
        val m = raw as? Map<*, *> ?: return null
        val out = LinkedHashMap<String, Any?>(m.size)
        for ((k, v) in m) {
            if (k == null) continue
            out[k.toString()] = v
        }
        return out
    }

    fun array(raw: Any?): List<Any?>? = (raw as? List<*>)?.toList()

    /** Binding-capable attribute: `@{expr}` wins, then static coercion. */
    fun <T : Any> attrValue(raw: Any?, coerce: (Any) -> T?): AttrValue<T>? {
        if (raw == null) return null
        bindingExpression(raw)?.let { return AttrValue.Binding(it) }
        val v = coerce(raw) ?: return null
        return AttrValue.Value(v)
    }
}''')

    for keywords in model.dimension_keyword_sets:
        parts.append("")
        parts.append(_dimension_type(keywords))

    return "\n".join(parts) + "\n"


def _dimension_type(keywords: tuple[str, ...]) -> str:
    name = dimension_type_name(keywords)
    lines = [
        f"/** `number | {' | '.join(repr(k) for k in keywords)}` union "
        "(used by dimension-style attributes). */",
        f"sealed class {name} {{",
        f"    data class Number(val value: Double) : {name}()",
    ]
    for k in keywords:
        lines.append(f"    object {_pascal(k)} : {name}()")
    lines += [
        "",
        "    companion object {",
        f"        fun parse(raw: Any?, context: String): {name}? {{",
        "            AttrCoerce.number(raw)?.let { return Number(it) }",
        "            val s = raw as? String ?: return null",
        "            return when (s) {",
    ]
    for k in keywords:
        lines.append(f"                {_kotlin_str(k)} -> {_pascal(k)}")
    lines += [
        "                else -> {",
        "                    AttrWarnings.emit(\"$context: unknown dimension keyword '$s'\")",
        "                    null",
        "                }",
        "            }",
        "        }",
        "    }",
        "}",
    ]
    return "\n".join(lines)


