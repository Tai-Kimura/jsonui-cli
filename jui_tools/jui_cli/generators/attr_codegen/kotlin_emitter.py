def _doc_comment(attr: Attribute) -> str:
    notes: list[str] = []
    if attr.required:
        notes.append("required")
    if attr.default is not None:
        notes.append(f"default: {attr.default}")
    if attr.aliases:
        notes.append("aliases: " + ", ".join(attr.aliases))
    if attr.binding_direction:
        notes.append(f"binding: {attr.binding_direction}")
    if attr.kind is AttrKind.RAW and attr.raw_kinds:
        notes.append("accepts: " + " | ".join(attr.raw_kinds))
    if attr.deprecated:
        note = attr.deprecation_note or "deprecated"
        notes.append(f"DEPRECATED: {note}")
    doc = attr.description
    if notes:
        doc = (doc + " " if doc else "") + "[" + "; ".join(notes) + "]"
    return doc


def _entry_name(value: str) -> str:
    """SCREAMING_SNAKE_CASE Kotlin enum entry from a JSON value."""
    words: list[str] = []
    for chunk in _split_words(value):
        if not chunk:
            continue
        # Split camelCase chunks into words.
        current = chunk[0]
        for ch in chunk[1:]:
            if ch.isupper() and not current[-1].isupper():
                words.append(current)
                current = ch
            else:
                current += ch
        words.append(current)
    name = "_".join(w.upper() for w in words) or "EMPTY"
    if name[0].isdigit():
        name = "V_" + name
    return name


def _escape_ident(name: str) -> str:
    if name in _KOTLIN_KEYWORDS:
        return f"`{name}`"
    return name


def _kotlin_str(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    )
    return f'"{escaped}"'
