def _component_file(comp: Component, model: AttrModel, mapper: TypeMapper) -> str:
    is_common = comp.name == "common"
    class_name = "CommonAttributes" if is_common else f"{comp.name}Attributes"

    parts = [HEADER.rstrip("\n"), "", f"package {PACKAGE}", ""]
    if is_common:
        parts.append("/** Attributes shared across all components (emitted once). */")
    else:
        parts.append(f"/** Typed attribute extraction for the `{comp.name}` component.")
        parts.append(" * Shared attributes are available via [common].")
        if comp.common_overrides:
            names = ", ".join(f"`{n}`" for n in comp.common_overrides)
            parts.append(
                f" * Overrides the common definition of: {names} "
                "(use the property on this class)."
            )
        parts.append(" */")

    parts.append(f"data class {class_name}(")
    ctor: list[str] = []
    if not is_common:
        ctor.append("    /** Attributes shared across all components. */")
        ctor.append("    val common: CommonAttributes,")
    for attr in comp.attrs:
        doc = _doc_comment(attr)
        if doc:
            ctor.append(f"    /** {doc} */")
        ctor.append(
            f"    val {_escape_ident(attr.name)}: {_prop_type(attr, mapper)}? = null,"
        )
    parts.extend(ctor)
    parts.append(") {")

    enums = [a for a in comp.attrs if a.kind is AttrKind.ENUM]
    for attr in enums:
        parts.extend(_enum_decl(attr))
        parts.append("")

    parts.append("    companion object {")
    parts.append(f"        fun parse(json: Map<String, Any?>): {class_name} = {class_name}(")
    if not is_common:
        parts.append("            common = CommonAttributes.parse(json),")
    for attr in comp.attrs:
        parts.append(
            f"            {_escape_ident(attr.name)} = {_parse_expr(attr)},"
        )
    parts.append("        )")
    for attr in enums:
        parts.append("")
        parts.extend(_enum_parse_func(attr))
    parts.append("    }")
    parts.append("}")
    return "\n".join(parts) + "\n"


def _enum_decl(attr: Attribute) -> list[str]:
    """Kotlin enum with a `from(raw)` mapping.

    Legacy value spellings that merge into one entry after identifier
    derivation (e.g. `"flow"` / `"Flow"`) all map to the same entry in
    `from`; `json` keeps the canonical (first-listed) spelling.
    """
    type_name = _pascal(attr.name)
    cases = enum_cases(attr.enum_values, _entry_name)
    lines = [f"    enum class {type_name}(val json: String) {{"]
    entries = [
        f"        {name}({_kotlin_str(canonical)})"
        for name, canonical, _ in cases
    ]
    lines.append(",\n".join(entries) + ";")
    lines += [
        "",
        "        companion object {",
        f"            fun from(raw: String): {type_name}? = when (raw) {{",
    ]
    for name, _, accepted in cases:
        rendered = ", ".join(_kotlin_str(v) for v in accepted)
        lines.append(f"                {rendered} -> {name}")
    lines += [
        "                else -> null",
        "            }",
        "        }",
        "    }",
    ]
    return lines


def _enum_parse_func(attr: Attribute) -> list[str]:
    type_name = _pascal(attr.name)
    return [
        f"        private fun parse{type_name}(raw: Any?): {type_name}? {{",
        "            val s = raw as? String ?: return null",
        f"            val v = {type_name}.from(s)",
        "            if (v == null) {",
        f"                AttrWarnings.emit(\"{attr.context}: unknown enum value '$s'\")",
        "            }",
        "            return v",
        "        }",
    ]


def _prop_type(attr: Attribute, mapper: TypeMapper) -> str:
    base = _base_type(attr, mapper)
    if attr.bindable:
        return f"AttrValue<{base}>"
    return base


def _base_type(attr: Attribute, mapper: TypeMapper) -> str:
    kind = attr.kind
    if kind in (AttrKind.STRING, AttrKind.COLOR, AttrKind.BINDING):
        return mapper.resolve_class("String", "android")
    if kind is AttrKind.NUMBER:
        return mapper.resolve_class("Double", "android")
    if kind is AttrKind.BOOLEAN:
        return mapper.resolve_class("Bool", "android")
    if kind is AttrKind.OBJECT:
        return "Map<String, Any?>"
    if kind is AttrKind.ARRAY:
        return "List<Any?>"
    if kind is AttrKind.ENUM:
        return _pascal(attr.name)
    if kind is AttrKind.DIMENSION:
        return dimension_type_name(attr.dimension_keywords)
    return "Any"  # ANY / RAW


def _parse_expr(attr: Attribute) -> str:
    aliases = ""
    if attr.aliases:
        rendered = ", ".join(_kotlin_str(a) for a in attr.aliases)
        aliases = f", listOf({rendered})"
    lookup = f"AttrCoerce.lookup(json, {_kotlin_str(attr.name)}{aliases})"

    kind = attr.kind
    if kind is AttrKind.BINDING:
        return f"AttrCoerce.bindingExprOrName({lookup})"

    coercers = {
        AttrKind.STRING: "AttrCoerce.string(it)",
        AttrKind.COLOR: "AttrCoerce.string(it)",
        AttrKind.NUMBER: "AttrCoerce.number(it)",
        AttrKind.BOOLEAN: "AttrCoerce.boolean(it)",
        AttrKind.OBJECT: "AttrCoerce.obj(it)",
        AttrKind.ARRAY: "AttrCoerce.array(it)",
        AttrKind.ANY: "it",
        AttrKind.RAW: "it",
    }
    if kind is AttrKind.ENUM:
        inner = f"parse{_pascal(attr.name)}(it)"
    elif kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        inner = f"{type_name}.parse(it, {_kotlin_str(attr.context)})"
    else:
        inner = coercers[kind]

    if attr.bindable:
        return f"AttrCoerce.attrValue({lookup}) {{ {inner} }}"

    if kind is AttrKind.ENUM:
        return f"parse{_pascal(attr.name)}({lookup})"
    if kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        return f"{type_name}.parse({lookup}, {_kotlin_str(attr.context)})"
    if kind in (AttrKind.ANY, AttrKind.RAW):
        return lookup
    call = inner.replace("(it)", "")
    return f"{call}({lookup})"


