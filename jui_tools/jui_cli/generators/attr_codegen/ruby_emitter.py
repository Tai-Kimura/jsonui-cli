def _component_file(comp: Component) -> str:
    is_common = comp.name == "common"
    module_name = "CommonAttributes" if is_common else f"{comp.name}Attributes"

    lines = [HEADER + "# frozen_string_literal: true", ""]
    lines.append(f"require_relative 'attr_support'")
    if not is_common:
        lines.append("require_relative 'common_attributes'")
    lines.append("")
    lines.append("module JsonUI")
    lines.append("  module Generated")
    if is_common:
        lines.append("    # Attributes shared across all components (emitted once).")
    else:
        lines.append(
            f"    # Typed attribute extraction for the `{comp.name}` component."
        )
        if comp.common_overrides:
            names = ", ".join(f"`{n}`" for n in comp.common_overrides)
            lines.append(
                f"    # Overrides the common definition of: {names}."
            )
    lines.append(f"    module {module_name}")
    lines.append("      ATTRS = [")
    for attr in comp.attrs:
        doc = _doc_comment(attr)
        if doc:
            lines.append(f"        # {doc}")
        lines.append(f"        {_row(attr)}.freeze,")
    lines.append("      ].freeze")
    lines.append("")
    lines.append("      # Returns a Hash keyed by canonical attribute name.")
    if is_common:
        lines.append("      def self.extract(hash)")
        lines.append("        AttrCoerce.extract_table(hash, ATTRS, 'common')")
        lines.append("      end")
    else:
        lines.append("      # Common attributes are merged first; component-level")
        lines.append("      # definitions override on name collision.")
        lines.append("      def self.extract(hash)")
        lines.append("        out = CommonAttributes.extract(hash)")
        lines.append(
            "        out.merge!(AttrCoerce.extract_table(hash, ATTRS, "
            f"{_ruby_str(comp.name)}))"
        )
        lines.append("        out")
        lines.append("      end")
    lines.append("    end")
    lines.append("  end")
    lines.append("end")
    return "\n".join(lines) + "\n"


def _row(attr: Attribute) -> str:
    parts = [f"name: {_ruby_str(attr.name)}", f"kind: :{_kind_symbol(attr)}"]
    if attr.bindable:
        parts.append("bindable: true")
    if attr.aliases:
        rendered = ", ".join(_ruby_str(a) for a in attr.aliases)
        parts.append(f"aliases: [{rendered}].freeze")
    if attr.kind is AttrKind.ENUM:
        rendered = ", ".join(_ruby_str(v) for v in attr.enum_values)
        parts.append(f"values: [{rendered}].freeze")
    if attr.kind is AttrKind.DIMENSION:
        rendered = ", ".join(_ruby_str(k) for k in attr.dimension_keywords)
        parts.append(f"keywords: [{rendered}].freeze")
    return "{ " + ", ".join(parts) + " }"


def _kind_symbol(attr: Attribute) -> str:
    return attr.kind.value


def _doc_comment(attr: Attribute) -> str:
    notes: list[str] = []
    if attr.required:
        notes.append("required")
    if attr.default is not None:
        notes.append(f"default: {attr.default}")
    if attr.binding_direction:
        notes.append(f"binding: {attr.binding_direction}")
    if attr.kind is AttrKind.RAW and attr.raw_kinds:
        notes.append("accepts: " + " | ".join(attr.raw_kinds))
    if attr.deprecated:
        note = attr.deprecation_note or "deprecated"
        notes.append(f"DEPRECATED: {note}")
    doc = attr.description
    if notes:
        doc = (doc + " " if doc else "") + "[" + "; ".join(notes) + "]"
    return doc


def _snake(name: str) -> str:
    out = ""
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0 and (
            not name[i - 1].isupper()
            or (i + 1 < len(name) and name[i + 1].islower())
        ):
            out += "_"
        out += ch.lower()
    return out


def _ruby_str(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"
