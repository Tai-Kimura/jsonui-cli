"""Swift emitter — typed attribute extraction structs (Swift 5.10+).

Emits, per :class:`~.model.AttrModel`:

- ``AttrCodegenSupport.swift`` — ``AttrValue<T>`` (value | binding), the
  ``AttrCodegenWarnings`` hook, ``AttrCoerce`` helpers, and the dimension
  union type(s) used by ``width`` / ``height``.
- ``CommonAttributes.swift`` — the 140+ shared attributes, emitted once.
- ``<Component>Attributes.swift`` — per-component diff; embeds
  ``CommonAttributes`` as ``.common``.

Style follows the SwiftJsonUI dynamic converter idiom: parse from
``[String: Any]`` (``JSONSerialization`` / ``DynamicComponent.rawData``
shape), never crash. Enum matching is lenient: case-insensitive, and
unknown values go through the warning hook and are passed through as
``AttrEnum.unknown`` (open-enum representation — author input is never
silently dropped). Binding-only attributes preserve their raw value in an
``AttrValue<Any>`` (``@{}`` wrapper recoverable, action objects kept).
``init(json:canonicalOnly:)`` disables alias fallback for L1-normalized
input, and ``declaredAttributes`` / ``aliasMap`` / ``isDeclared`` are the
public metadata contract.
"""
from __future__ import annotations

from ...core.type_mapper import TypeMapper
from .model import Attribute, AttrKind, AttrModel, Component, merged_alias_map

HEADER = (
    "// @generated by `jui generate attr-bindings` — DO NOT EDIT BY HAND.\n"
    "// Source of truth: shared/core/attribute_definitions.json\n"
    "// Regenerate: jui generate attr-bindings --lang swift\n"
)

_SWIFT_KEYWORDS = frozenset({
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate",
    "func", "import", "init", "inout", "internal", "let", "open", "operator",
    "private", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "catch", "continue",
    "default", "defer", "do", "else", "fallthrough", "for", "guard", "if",
    "in", "repeat", "return", "switch", "throw", "where", "while", "as",
    "any", "false", "is", "nil", "self", "super", "true", "try", "Self",
    "Any", "Type", "Protocol",
    # Contextual keywords that still break stored-property declarations.
    "lazy",
})


def emit(model: AttrModel) -> dict[str, str]:
    """Return ``{relative_path: content}`` for the Swift output (sorted)."""
    mapper = TypeMapper()
    files: dict[str, str] = {}
    files["AttrCodegenSupport.swift"] = _support_file(model)
    files["CommonAttributes.swift"] = _component_file(model.common, model, mapper)
    for comp in model.components:
        files[f"{comp.name}Attributes.swift"] = _component_file(comp, model, mapper)
    return dict(sorted(files.items()))


