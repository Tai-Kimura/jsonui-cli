# Naming / escaping
# ---------------------------------------------------------------------------

def _doc_comment(attr: Attribute) -> str:
    notes: list[str] = []
    if attr.required:
        notes.append("required")
    if attr.default is not None:
        notes.append(f"default: {attr.default}")
    if attr.aliases:
        notes.append("aliases: " + ", ".join(attr.aliases))
    if attr.binding_direction:
        notes.append(f"binding: {attr.binding_direction}")
    if attr.kind is AttrKind.RAW and attr.raw_kinds:
        notes.append("accepts: " + " | ".join(attr.raw_kinds))
    if attr.deprecated:
        note = attr.deprecation_note or "deprecated"
        notes.append(f"DEPRECATED: {note}")
    doc = attr.description
    if notes:
        doc = (doc + " " if doc else "") + "[" + "; ".join(notes) + "]"
    return doc


def _pascal(name: str) -> str:
    chunks = [c for c in _split_words(name) if c]
    return "".join(c[:1].upper() + c[1:] for c in chunks)


def _split_words(name: str) -> list[str]:
    out: list[str] = []
    current = ""
    for ch in name:
        if ch.isalnum():
            current += ch
        else:
            out.append(current)
            current = ""
    out.append(current)
    return out


def _case_name(value: str) -> str:
    """Swift enum case name for an enum/keyword JSON value."""
    words = [w for w in _split_words(value) if w]
    if not words:
        name = "empty"
    else:
        name = words[0][:1].lower() + words[0][1:]
        for w in words[1:]:
            name += w[:1].upper() + w[1:]
    if name[0].isdigit():
        name = "v" + name
    return _escape_ident(name)


def _escape_ident(name: str) -> str:
    if name in _SWIFT_KEYWORDS:
        return f"`{name}`"
    return name


def _swift_str(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
