"""Swift emitter — typed attribute extraction structs (Swift 5.10+).

Emits, per :class:`~.model.AttrModel`:

- ``AttrCodegenSupport.swift`` — ``AttrValue<T>`` (value | binding), the
  ``AttrCodegenWarnings`` hook, ``AttrCoerce`` helpers, and the dimension
  union type(s) used by ``width`` / ``height``.
- ``CommonAttributes.swift`` — the 140+ shared attributes, emitted once.
- ``<Component>Attributes.swift`` — per-component diff; embeds
  ``CommonAttributes`` as ``.common``.

Style follows the SwiftJsonUI dynamic converter idiom: parse from
``[String: Any]`` (``JSONSerialization`` / ``DynamicComponent.rawData``
shape), never crash — unknown enum values become ``nil`` and go through the
warning hook.
"""
from __future__ import annotations

from ...core.type_mapper import TypeMapper
from .model import Attribute, AttrKind, AttrModel, Component

HEADER = (
    "// @generated by `jui generate attr-bindings` — DO NOT EDIT BY HAND.\n"
    "// Source of truth: shared/core/attribute_definitions.json\n"
    "// Regenerate: jui generate attr-bindings --lang swift\n"
)

_SWIFT_KEYWORDS = frozenset({
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate",
    "func", "import", "init", "inout", "internal", "let", "open", "operator",
    "private", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "catch", "continue",
    "default", "defer", "do", "else", "fallthrough", "for", "guard", "if",
    "in", "repeat", "return", "switch", "throw", "where", "while", "as",
    "any", "false", "is", "nil", "self", "super", "true", "try", "Self",
    "Any", "Type", "Protocol",
    # Contextual keywords that still break stored-property declarations.
    "lazy",
})


def emit(model: AttrModel) -> dict[str, str]:
    """Return ``{relative_path: content}`` for the Swift output (sorted)."""
    mapper = TypeMapper()
    files: dict[str, str] = {}
    files["AttrCodegenSupport.swift"] = _support_file(model)
    files["CommonAttributes.swift"] = _component_file(model.common, model, mapper)
    for comp in model.components:
        files[f"{comp.name}Attributes.swift"] = _component_file(comp, model, mapper)
    return dict(sorted(files.items()))


# ---------------------------------------------------------------------------
# Support file
# ---------------------------------------------------------------------------

def _support_file(model: AttrModel) -> str:
    parts = [HEADER.rstrip("\n"), "", "import Foundation", ""]
    parts.append('''\
/// Static value or `@{binding}` expression for a binding-capable attribute.
public enum AttrValue<T> {
    case value(T)
    /// The expression inside `@{...}` (without the wrapper).
    case binding(String)

    public var value: T? {
        if case .value(let v) = self { return v }
        return nil
    }

    public var bindingExpression: String? {
        if case .binding(let e) = self { return e }
        return nil
    }
}

/// Warning hook — generated parsers never crash on malformed input.
/// Unknown enum values / dimension keywords are reported here and parsed
/// as `nil`.
public enum AttrCodegenWarnings {
    public static var handler: ((String) -> Void)?

    public static func emit(_ message: String) {
        handler?(message)
    }
}

/// Coercion helpers used by the generated `init(json:)` implementations.
public enum AttrCoerce {
    /// Canonical-name lookup with alias fallback (aliases are resolved in
    /// generated code so raw / non-normalized JSON keeps working).
    public static func lookup(
        _ json: [String: Any], _ canonical: String, _ aliases: [String] = []
    ) -> Any? {
        if let v = json[canonical], !(v is NSNull) { return v }
        for alias in aliases {
            if let v = json[alias], !(v is NSNull) { return v }
        }
        return nil
    }

    /// `"@{expr}"` → `"expr"`; anything else → `nil`.
    public static func bindingExpression(_ raw: Any?) -> String? {
        guard let s = raw as? String,
              s.hasPrefix("@{"), s.hasSuffix("}"), s.count > 3 else {
            return nil
        }
        return String(s.dropFirst(2).dropLast(1))
    }

    /// Binding-only attributes accept `@{fn}` (canonical) or a bare name.
    public static func bindingExprOrName(_ raw: Any?) -> String? {
        return bindingExpression(raw) ?? string(raw)
    }

    public static func string(_ raw: Any?) -> String? {
        return raw as? String
    }

    public static func number(_ raw: Any?) -> Double? {
        if let d = raw as? Double { return d }
        if let i = raw as? Int { return Double(i) }
        if let n = raw as? NSNumber { return n.doubleValue }
        return nil
    }

    public static func boolean(_ raw: Any?) -> Bool? {
        return raw as? Bool
    }

    public static func object(_ raw: Any?) -> [String: Any]? {
        return raw as? [String: Any]
    }

    public static func array(_ raw: Any?) -> [Any]? {
        return raw as? [Any]
    }

    public static func any(_ raw: Any?) -> Any? {
        if raw is NSNull { return nil }
        return raw
    }

    /// Binding-capable attribute: `@{expr}` wins, then static coercion.
    public static func attrValue<T>(
        _ raw: Any?, _ coerce: (Any) -> T?
    ) -> AttrValue<T>? {
        guard let raw = raw, !(raw is NSNull) else { return nil }
        if let expr = bindingExpression(raw) { return .binding(expr) }
        if let v = coerce(raw) { return .value(v) }
        return nil
    }
}''')

    for keywords in model.dimension_keyword_sets:
        parts.append("")
        parts.append(_dimension_type(keywords))

    return "\n".join(parts) + "\n"


def dimension_type_name(keywords: tuple[str, ...]) -> str:
    """Deterministic Swift/Kotlin type name for a number|keyword union."""
    if set(keywords) == {"matchParent", "wrapContent"}:
        return "DimensionValue"
    return "NumberOr" + "".join(_pascal(k) for k in sorted(keywords))


def _dimension_type(keywords: tuple[str, ...]) -> str:
    name = dimension_type_name(keywords)
    lines = [
        f"/// `number | {' | '.join(repr(k) for k in keywords)}` union "
        "(used by dimension-style attributes).",
        f"public enum {name}: Equatable {{",
        "    case number(Double)",
    ]
    for k in keywords:
        lines.append(f"    case {_case_name(k)}")
    lines += [
        "",
        f"    public static func parse(_ raw: Any?, _ context: String) -> {name}? {{",
        "        if let n = AttrCoerce.number(raw) { return .number(n) }",
        "        guard let s = raw as? String else { return nil }",
        "        switch s {",
    ]
    for k in keywords:
        lines.append(f'        case {_swift_str(k)}: return .{_case_name(k)}')
    lines += [
        "        default:",
        "            AttrCodegenWarnings.emit(\"\\(context): unknown dimension keyword '\\(s)'\")",
        "            return nil",
        "        }",
        "    }",
        "}",
    ]
    return "\n".join(lines)


