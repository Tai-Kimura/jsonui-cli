def _component_file(comp: Component, model: AttrModel, mapper: TypeMapper) -> str:
    is_common = comp.name == "common"
    struct_name = "CommonAttributes" if is_common else f"{comp.name}Attributes"

    parts = [HEADER.rstrip("\n"), "", "import Foundation", ""]
    if is_common:
        parts.append("/// Attributes shared across all components (emitted once).")
    else:
        parts.append(f"/// Typed attribute extraction for the `{comp.name}` component.")
        if comp.alias_of:
            parts.append(
                f"/// Component alias of `{comp.alias_of}` — full clone of the "
                "canonical table (the runtime selects tables by raw spelling)."
            )
        parts.append("/// Shared attributes are available via `common`.")
        if comp.common_overrides:
            names = ", ".join(f"`{n}`" for n in comp.common_overrides)
            parts.append(
                f"/// Overrides the common definition of: {names} "
                "(use the property on this struct)."
            )
    parts.append(f"public struct {struct_name} {{")

    body: list[str] = []
    enums = [a for a in comp.attrs if a.kind is AttrKind.ENUM]
    for attr in enums:
        body.extend(_enum_decl(attr))
        body.append("")

    body.extend(_metadata_decls(comp, model))
    body.append("")

    if not is_common:
        body.append("    /// Attributes shared across all components.")
        body.append("    public let common: CommonAttributes")
        body.append("")

    for attr in comp.attrs:
        doc = _doc_comment(attr)
        if doc:
            body.append(f"    /// {doc}")
        prop = _escape_ident(attr.name)
        body.append(f"    public let {prop}: {_prop_type(attr, mapper)}?")
        body.append("")

    body.append("    /// Pass `canonicalOnly: true` for L1-normalized input —")
    body.append("    /// alias fallback is then disabled.")
    body.append("    public init(json: [String: Any], canonicalOnly: Bool = false) {")
    if not is_common:
        body.append(
            "        self.common = CommonAttributes(json: json, "
            "canonicalOnly: canonicalOnly)"
        )
    for attr in comp.attrs:
        body.append(f"        self.{_escape_ident(attr.name)} = {_parse_expr(attr)}")
    body.append("    }")

    for attr in enums:
        body.append("")
        body.extend(_enum_parse_func(attr))

    parts.extend(body)
    parts.append("}")
    return "\n".join(parts) + "\n"


def _metadata_decls(comp: Component, model: AttrModel) -> list[str]:
    """`declaredAttributes` / `aliasMap` / `isDeclared` — the public
    metadata contract (mirrors the Ruby `rows`/`declared?`/`alias_map`
    helpers)."""
    is_common = comp.name == "common"
    own = sorted(a.name for a in comp.attrs)
    alias_map = merged_alias_map(comp, None if is_common else model.common)

    lines = [
        "    /// Canonical attribute names declared for this component"
        + ("" if is_common else ", including the shared `common` set")
        + " (public metadata contract).",
    ]
    if is_common:
        lines.append("    public static let declaredAttributes: Set<String> = [")
    else:
        lines.append(
            "    public static let declaredAttributes: Set<String> = "
            "CommonAttributes.declaredAttributes.union(["
        )
    for name in own:
        lines.append(f"        {_swift_str(name)},")
    lines.append("    ]" + ("" if is_common else ")"))
    lines.append("")
    lines.append("    /// Alias spelling → canonical attribute name"
                 + ("" if is_common else " (merged with common)")
                 + ". Alias")
    lines.append("    /// spellings that are also declared attributes keep their own")
    lines.append("    /// entry and are not redirected.")
    if alias_map:
        lines.append("    public static let aliasMap: [String: String] = [")
        for alias, canonical in alias_map.items():
            lines.append(f"        {_swift_str(alias)}: {_swift_str(canonical)},")
        lines.append("    ]")
    else:
        lines.append("    public static let aliasMap: [String: String] = [:]")
    lines.append("")
    lines.append("    /// True when `key` is a declared canonical name or alias spelling.")
    lines.append("    public static func isDeclared(_ key: String) -> Bool {")
    lines.append("        return declaredAttributes.contains(key) || aliasMap[key] != nil")
    lines.append("    }")
    return lines


def enum_cases(
    values: tuple[str, ...],
    namer,
    value_aliases: dict[str, str] | None = None,
) -> list[tuple[str, str, list[str]]]:
    """Dedupe enum values by derived case name.

    The definitions file keeps legacy spellings next to canonical ones
    (e.g. Collection.layout has both ``"flow"`` and ``"Flow"``); after
    identifier derivation those merge into one case. Declared
    ``valueAliases`` fold BEFORE naming, so an alias spelling with its own
    identifier (``LeftAligned``) still lands in its canonical value's case
    (``flow``) and every runtime routes it through the canonical code path.
    Returns ``[(case_name, canonical_value, [all_accepted_values])]`` in
    first-seen order (deterministic — definition order is stable).
    """
    value_aliases = value_aliases or {}
    ordered: list[tuple[str, str, list[str]]] = []
    by_name: dict[str, list[str]] = {}
    for value in values:
        canonical = value_aliases.get(value, value)
        name = namer(canonical)
        if name in by_name:
            if value not in by_name[name]:
                by_name[name].append(value)
        else:
            accepted = [value] if value == canonical else [canonical, value]
            by_name[name] = accepted
            ordered.append((name, canonical, accepted))
    return ordered


def enum_ci_cases(
    values: tuple[str, ...],
    namer,
    value_aliases: dict[str, str] | None = None,
) -> list[tuple[str, list[str]]]:
    """Case-insensitive match table: ``[(case_name, [lowered values])]``.

    Lenient enum matching switches on the lowercased raw value, so the
    accepted spellings are lowercased and deduped globally (first-seen
    case wins on a collision — definition order is stable, so this is
    deterministic).
    """
    seen: set[str] = set()
    out: list[tuple[str, list[str]]] = []
    for case_name, _, accepted in enum_cases(values, namer, value_aliases):
        lowered: list[str] = []
        for value in accepted:
            lv = value.lower()
            if lv not in seen:
                seen.add(lv)
                lowered.append(lv)
        if lowered:
            out.append((case_name, lowered))
    return out


def _enum_decl(attr: Attribute) -> list[str]:
    type_name = _pascal(attr.name)
    lines = [f"    public enum {type_name}: String {{"]
    for case_name, canonical, _ in enum_cases(attr.enum_values, _case_name, attr.value_alias_map):
        lines.append(f"        case {case_name} = {_swift_str(canonical)}")
    lines.append("    }")
    return lines


def _enum_parse_func(attr: Attribute) -> list[str]:
    """Lenient enum parse: case-insensitive match; unknown values warn and
    pass through as `.unknown` (never dropped)."""
    type_name = _pascal(attr.name)
    lines = [
        f"    private static func parse{type_name}(_ raw: Any?) -> AttrEnum<{type_name}>? {{",
        "        guard let raw = raw, !(raw is NSNull) else { return nil }",
        "        if let s = raw as? String {",
        "            switch s.lowercased() {",
    ]
    for case_name, lowered in enum_ci_cases(attr.enum_values, _case_name, attr.value_alias_map):
        rendered = ", ".join(_swift_str(v) for v in lowered)
        # Fully qualified (`TypeName.case`) — a bare `.none` in this
        # position is ambiguous with `Optional.none`.
        lines.append(
            f"            case {rendered}: return .known({type_name}.{case_name})"
        )
    lines += [
        "            default: break",
        "            }",
        "        }",
        f"        AttrCodegenWarnings.emit(\"{attr.context}: unknown enum value '\\(raw)'\")",
        "        return .unknown(raw)",
        "    }",
    ]
    return lines


def _prop_type(attr: Attribute, mapper: TypeMapper) -> str:
    if attr.kind is AttrKind.BINDING:
        # Binding-only: `@{expr}` or the raw value (bare name / action
        # object) — the wrapper information is preserved.
        return "AttrValue<Any>"
    base = _base_type(attr, mapper)
    if attr.bindable:
        return f"AttrValue<{base}>"
    return base


def _base_type(attr: Attribute, mapper: TypeMapper) -> str:
    kind = attr.kind
    if kind in (AttrKind.STRING, AttrKind.COLOR):
        return mapper.resolve_class("String", "ios")
    if kind is AttrKind.NUMBER:
        return mapper.resolve_class("Double", "ios")
    if kind is AttrKind.BOOLEAN:
        return mapper.resolve_class("Bool", "ios")
    if kind is AttrKind.OBJECT:
        return "[String: Any]"
    if kind is AttrKind.ARRAY:
        return "[Any]"
    if kind is AttrKind.ENUM:
        return f"AttrEnum<{_pascal(attr.name)}>"
    if kind is AttrKind.DIMENSION:
        return dimension_type_name(attr.dimension_keywords)
    return "Any"  # ANY / RAW


def _parse_expr(attr: Attribute) -> str:
    if attr.aliases:
        rendered = ", ".join(_swift_str(a) for a in attr.aliases)
        lookup = (
            f"AttrCoerce.lookup(json, {_swift_str(attr.name)}, [{rendered}], "
            "canonicalOnly: canonicalOnly)"
        )
    else:
        # No aliases declared — canonicalOnly is a no-op for this attr.
        lookup = f"AttrCoerce.lookup(json, {_swift_str(attr.name)})"

    kind = attr.kind
    if kind is AttrKind.BINDING:
        return f"AttrCoerce.bindingValue({lookup})"

    if kind is AttrKind.ENUM:
        inner = f"Self.parse{_pascal(attr.name)}"
    elif kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        inner = f"{{ {type_name}.parse($0, {_swift_str(attr.context)}) }}"
    elif kind in (AttrKind.STRING, AttrKind.COLOR):
        inner = "AttrCoerce.string"
    elif kind is AttrKind.NUMBER:
        inner = "AttrCoerce.number"
    elif kind is AttrKind.BOOLEAN:
        inner = "AttrCoerce.boolean"
    elif kind is AttrKind.OBJECT:
        inner = "AttrCoerce.object"
    elif kind is AttrKind.ARRAY:
        inner = "AttrCoerce.array"
    else:  # ANY / RAW
        inner = "{ $0 }"

    if attr.bindable:
        if kind is AttrKind.ENUM:
            inner = f"{{ Self.parse{_pascal(attr.name)}($0) }}"
        return f"AttrCoerce.attrValue({lookup}, {inner})"

    if kind is AttrKind.ENUM:
        return f"Self.parse{_pascal(attr.name)}({lookup})"
    if kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        return f"{type_name}.parse({lookup}, {_swift_str(attr.context)})"
    if kind in (AttrKind.ANY, AttrKind.RAW):
        return f"AttrCoerce.any({lookup})"
    return f"{inner}({lookup})"


