def _component_file(comp: Component, model: AttrModel, mapper: TypeMapper) -> str:
    is_common = comp.name == "common"
    struct_name = "CommonAttributes" if is_common else f"{comp.name}Attributes"

    parts = [HEADER.rstrip("\n"), "", "import Foundation", ""]
    if is_common:
        parts.append("/// Attributes shared across all components (emitted once).")
    else:
        parts.append(f"/// Typed attribute extraction for the `{comp.name}` component.")
        parts.append("/// Shared attributes are available via `common`.")
        if comp.common_overrides:
            names = ", ".join(f"`{n}`" for n in comp.common_overrides)
            parts.append(
                f"/// Overrides the common definition of: {names} "
                "(use the property on this struct)."
            )
    parts.append(f"public struct {struct_name} {{")

    body: list[str] = []
    enums = [a for a in comp.attrs if a.kind is AttrKind.ENUM]
    for attr in enums:
        body.extend(_enum_decl(attr))
        body.append("")

    if not is_common:
        body.append("    /// Attributes shared across all components.")
        body.append("    public let common: CommonAttributes")
        body.append("")

    for attr in comp.attrs:
        doc = _doc_comment(attr)
        if doc:
            body.append(f"    /// {doc}")
        prop = _escape_ident(attr.name)
        body.append(f"    public let {prop}: {_prop_type(attr, mapper)}?")
        body.append("")

    body.append("    public init(json: [String: Any]) {")
    if not is_common:
        body.append("        self.common = CommonAttributes(json: json)")
    for attr in comp.attrs:
        body.append(f"        self.{_escape_ident(attr.name)} = {_parse_expr(attr)}")
    body.append("    }")

    for attr in enums:
        body.append("")
        body.extend(_enum_parse_func(attr))

    parts.extend(body)
    parts.append("}")
    return "\n".join(parts) + "\n"


def enum_cases(values: tuple[str, ...], namer) -> list[tuple[str, str, list[str]]]:
    """Dedupe enum values by derived case name.

    The definitions file keeps legacy spellings next to canonical ones
    (e.g. Collection.layout has both ``"flow"`` and ``"Flow"``); after
    identifier derivation those merge into one case. Returns
    ``[(case_name, canonical_value, [all_accepted_values])]`` in first-seen
    order (deterministic — definition order is stable).
    """
    ordered: list[tuple[str, str, list[str]]] = []
    by_name: dict[str, list[str]] = {}
    for value in values:
        name = namer(value)
        if name in by_name:
            by_name[name].append(value)
        else:
            accepted = [value]
            by_name[name] = accepted
            ordered.append((name, value, accepted))
    return ordered


def _enum_decl(attr: Attribute) -> list[str]:
    type_name = _pascal(attr.name)
    lines = [f"    public enum {type_name}: String {{"]
    for case_name, canonical, _ in enum_cases(attr.enum_values, _case_name):
        lines.append(f"        case {case_name} = {_swift_str(canonical)}")
    lines.append("    }")
    return lines


def _enum_parse_func(attr: Attribute) -> list[str]:
    type_name = _pascal(attr.name)
    lines = [
        f"    private static func parse{type_name}(_ raw: Any?) -> {type_name}? {{",
        "        guard let s = raw as? String else { return nil }",
        "        switch s {",
    ]
    for case_name, _, accepted in enum_cases(attr.enum_values, _case_name):
        rendered = ", ".join(_swift_str(v) for v in accepted)
        # Fully qualified (`TypeName.case`) — a bare `.none` in an
        # Optional-returning function is ambiguous with `Optional.none`.
        lines.append(f"        case {rendered}: return {type_name}.{case_name}")
    lines += [
        "        default:",
        f"            AttrCodegenWarnings.emit(\"{attr.context}: unknown enum value '\\(s)'\")",
        "            return nil",
        "        }",
        "    }",
    ]
    return lines


def _prop_type(attr: Attribute, mapper: TypeMapper) -> str:
    base = _base_type(attr, mapper)
    if attr.bindable:
        return f"AttrValue<{base}>"
    return base


def _base_type(attr: Attribute, mapper: TypeMapper) -> str:
    kind = attr.kind
    if kind in (AttrKind.STRING, AttrKind.COLOR, AttrKind.BINDING):
        return mapper.resolve_class("String", "ios")
    if kind is AttrKind.NUMBER:
        return mapper.resolve_class("Double", "ios")
    if kind is AttrKind.BOOLEAN:
        return mapper.resolve_class("Bool", "ios")
    if kind is AttrKind.OBJECT:
        return "[String: Any]"
    if kind is AttrKind.ARRAY:
        return "[Any]"
    if kind is AttrKind.ENUM:
        return _pascal(attr.name)
    if kind is AttrKind.DIMENSION:
        return dimension_type_name(attr.dimension_keywords)
    return "Any"  # ANY / RAW


def _parse_expr(attr: Attribute) -> str:
    aliases = ""
    if attr.aliases:
        rendered = ", ".join(_swift_str(a) for a in attr.aliases)
        aliases = f", [{rendered}]"
    lookup = f"AttrCoerce.lookup(json, {_swift_str(attr.name)}{aliases})"

    kind = attr.kind
    if kind is AttrKind.BINDING:
        return f"AttrCoerce.bindingExprOrName({lookup})"

    if kind is AttrKind.ENUM:
        inner = f"Self.parse{_pascal(attr.name)}"
    elif kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        inner = f"{{ {type_name}.parse($0, {_swift_str(attr.context)}) }}"
    elif kind in (AttrKind.STRING, AttrKind.COLOR):
        inner = "AttrCoerce.string"
    elif kind is AttrKind.NUMBER:
        inner = "AttrCoerce.number"
    elif kind is AttrKind.BOOLEAN:
        inner = "AttrCoerce.boolean"
    elif kind is AttrKind.OBJECT:
        inner = "AttrCoerce.object"
    elif kind is AttrKind.ARRAY:
        inner = "AttrCoerce.array"
    else:  # ANY / RAW
        inner = "{ $0 }"

    if attr.bindable:
        if kind is AttrKind.ENUM:
            inner = f"{{ Self.parse{_pascal(attr.name)}($0) }}"
        return f"AttrCoerce.attrValue({lookup}, {inner})"

    if kind is AttrKind.ENUM:
        return f"Self.parse{_pascal(attr.name)}({lookup})"
    if kind is AttrKind.DIMENSION:
        type_name = dimension_type_name(attr.dimension_keywords)
        return f"{type_name}.parse({lookup}, {_swift_str(attr.context)})"
    if kind in (AttrKind.ANY, AttrKind.RAW):
        return f"AttrCoerce.any({lookup})"
    return f"{inner}({lookup})"


