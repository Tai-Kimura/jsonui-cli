"""`jui lint-generated` and the files jsonui-test writes into the same `Generated/` folders (ticket
2026-10-21-lint-generated-red-on-branch-tests-without-footer).

The header/footer contract (core/generated_marker.py) is jui/sjui/kjui/rjui's. jsonui-test's branch tests carry a
one-line banner and no footer, and `jsonui-test generate branch-tests --check` compares every byte of them; its harness
skeletons (iOS default `Tests/Generated`, beside the tests) are consumer-owned. Before the fix a project that followed
invariant 5 was red here: footer missing on every branch test and runtime, header missing on every iOS harness.
These arms: the branch test and runtime are green without a footer; the skeleton is not counted; a jui file with its
footer removed by hand is still red, and so is a jsonui-test banner below the head (not this tool's file layout); and the
two strings are the ones test_tools writes, read from its source in this checkout.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from jui_cli.commands import lint_generated_cmd as lg
from jui_cli.commands.lint_generated_cmd import EXIT_HEALTH, EXIT_OK, cmd_lint_generated

REPO = Path(__file__).resolve().parents[2]
BRANCH_TESTS = REPO / "test_tools" / "jsonui_test_cli" / "branch_tests.py"

FOOTER = "// ══ END AUTO-GENERATED — DO NOT APPEND BELOW THIS LINE ══\n"
JUI_FILE = "// @generated AUTO-GENERATED FILE — DO NOT EDIT\nexport const thing = 1;\n" + FOOTER
SWIFT_TEST = ("// @generated by `jsonui-test generate branch-tests cart --platform ios` — DO NOT EDIT.\n"
              "import XCTest\n@testable import Shop\n\nfinal class CartBranchesTest: XCTestCase {}\n")
SWIFT_RUNTIME = "// @generated by `jsonui-test generate branch-tests --platform ios` — DO NOT EDIT.\nimport XCTest\n"
SWIFT_HARNESS = ("// Branch-contract test harness for `cart` — CONSUMER-OWNED.\n"
                 "// Generated once as a skeleton by `jsonui-test generate branch-tests`;\n"
                 "// edit freely, it will not be overwritten.\nimport XCTest\n")
TS_TEST = "// @generated by `jsonui-test generate branch-tests cart` — DO NOT EDIT.\nimport { it } from 'vitest';\n"


def _project(root: Path) -> Path:
    (root / "jui.config.json").write_text(json.dumps({"platforms": {"ios": {"root": "ios"}, "web": {"root": "web"}}}), encoding="utf-8")
    ios = root / "ios" / "Tests" / "Generated"
    ios.mkdir(parents=True)
    (ios / "CartBranchesTest.swift").write_text(SWIFT_TEST, encoding="utf-8")
    (ios / "JsonuiBranchRuntime.swift").write_text(SWIFT_RUNTIME, encoding="utf-8")
    (ios / "CartBranchHarness.swift").write_text(SWIFT_HARNESS, encoding="utf-8")
    web = root / "web" / "tests" / "unit" / "Generated"
    web.mkdir(parents=True)
    (web / "cart.branches.test.ts").write_text(TS_TEST, encoding="utf-8")
    hooks = root / "web" / "src" / "generated" / "hooks"
    hooks.mkdir(parents=True)
    (hooks / "useThing.ts").write_text(JUI_FILE, encoding="utf-8")
    return root


def _run(root: Path, monkeypatch, capsys) -> tuple[int, str]:
    monkeypatch.chdir(root)
    args = argparse.Namespace(fix=False, verbose=False, max_depth=5, max_lines=250, update_size_baseline=False, fail_on="any")
    code = cmd_lint_generated(args)
    return code, capsys.readouterr().out


def test_jsonui_test_branch_tests_and_runtime_pass_without_a_footer(tmp_path, monkeypatch, capsys):
    code, out = _run(_project(tmp_path), monkeypatch, capsys)
    assert code == EXIT_OK, out
    assert "Checked 4 generated files" in out          # the harness skeleton is not one of them
    assert "Missing footer:  0" in out and "Missing header:  0" in out
    assert "Not checked:     1 (jsonui-test harness skeletons, consumer-owned)" in out


def test_a_jui_file_with_its_footer_removed_is_still_red(tmp_path, monkeypatch, capsys):
    root = _project(tmp_path)
    (root / "web" / "src" / "generated" / "hooks" / "useThing.ts").write_text(JUI_FILE.replace(FOOTER, ""), encoding="utf-8")
    code, out = _run(root, monkeypatch, capsys)
    assert code == EXIT_HEALTH
    assert "Missing footer:  1" in out and "useThing.ts" in out


def test_a_jsonui_test_banner_below_the_head_is_not_this_tools_file(tmp_path, monkeypatch, capsys):
    root = _project(tmp_path)
    body = "\n".join(f"let x{i} = {i}" for i in range(lg.HEAD_SCAN_LINES + 5)) + "\n"
    (root / "ios" / "Tests" / "Generated" / "CartBranchesTest.swift").write_text(body + SWIFT_TEST, encoding="utf-8")
    code, out = _run(root, monkeypatch, capsys)
    assert code == EXIT_HEALTH
    assert "Missing header:  1" in out and "CartBranchesTest.swift" in out


def test_a_hand_written_file_in_the_folder_is_still_red(tmp_path, monkeypatch, capsys):
    root = _project(tmp_path)
    (root / "ios" / "Tests" / "Generated" / "Mine.swift").write_text("import XCTest\n", encoding="utf-8")
    code, out = _run(root, monkeypatch, capsys)
    assert code == EXIT_HEALTH
    assert "Missing header:  1" in out and "Mine.swift" in out


def test_the_strings_are_the_ones_jsonui_test_writes():
    src = BRANCH_TESTS.read_text(encoding="utf-8")
    assert f'GENERATED_MARKER = "{lg.JSONUI_TEST_BANNER}"' in src
    # every banner the generator writes (test and runtime, three platforms) starts with it
    banners = [line for line in src.splitlines() if "@generated by `jsonui-test" in line and "DO NOT EDIT" in line]
    assert len(banners) >= 6 and all(lg.JSONUI_TEST_BANNER in b for b in banners), banners
    # every harness skeleton (ts, kotlin, swift) carries the skeleton line and no @generated
    for name in ("HARNESS_SKELETON = '''", "KOTLIN_HARNESS_SKELETON = '''", "SWIFT_HARNESS_SKELETON = '''"):
        start = src.index(name)
        head = "\n".join(src[start:].splitlines()[:3])
        assert lg.JSONUI_TEST_SKELETON in head and "@generated" not in head, (name, head)
