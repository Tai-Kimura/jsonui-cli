def _render_kotlin_branch(
    pascal: str, method_name: str, params: list[str], contract: dict,
    row: "Row", conditions: dict, *, screen: str,
) -> list[str]:
    branch = row.branch
    number = row.number
    when = branch.get("when") or {}
    then = branch.get("then") or {}
    state, seed = _arrange_state(contract, branch, conditions)
    overrides = {k[len("api."):]: v for k, v in when.items() if k.startswith("api.")}
    arg_values = {k[len("arg."):]: v for k, v in when.items() if k.startswith("arg.")}
    args = [
        _kt(arg_values.get(p)) if p in arg_values else "null"
        for p in params
    ]
    while args and args[-1] == "null":
        args.pop()
    data_refs = _collect_data_refs(then)
    name = f"{method_name} branch {number}"
    if row.also is not None:
        name += f" also {row.also[0]}"
    if row.control_of:
        name += " control"

    out: list[str] = []
    out.append("")
    out.append(f"  // {_row_title(contract, row)}")
    out.append(f"  @Test fun `{name}`() {{")
    if row.conditions:
        # Harness conditions (design v4.11, P2d): the factory is wrapped so
        # the hook runs after the server is serving and before the harness
        # is built — runBranchTest itself is unchanged.
        out.append(
            f"    runBranchTest(routes, {_kt({k: v for k, v in overrides.items()})}, "
            "{ baseUrl, dispatcher ->"
        )
        for cname, cvalue in row.conditions:
            out.append(f"      arrangeCondition({_kt_str(cname)}, {_kt_str(cvalue)})")
        out.append(f"      create{pascal}BranchHarness(baseUrl, dispatcher)")
        out.append("    }) { h, rec ->")
    else:
        out.append(
            f"    runBranchTest(routes, {_kt({k: v for k, v in overrides.items()})}, "
            f"::create{pascal}BranchHarness) {{ h, rec ->"
        )
    # The act window (see the web emitter): the harness was built with the
    # server already serving; its construction settles, the arrangement goes
    # in, and the recorder starts counting only then.
    out.append("      h.settle()")
    if state:
        out.append(f"      h.setState({_kt(state)})")
    if seed:
        out.append(f"      seedState(h, {_kt(seed)})")
    out.append("      rec.mark()")
    for fname in data_refs:
        out.append(f"      val ref_{fname} = h.readField({_kt_str(fname)})")
    call_args = ", ".join(args)
    act_start = len(out)
    out.append(f"      h.invoke({_kt_str(method_name)}{', ' + call_args if call_args else ''})")
    out.append("      h.settle()")

    # See the web emitter: reach is asserted before the `then` entries so an
    # unreached route is reported as such, not as a wrong value.
    for op in _unspoken_when_ops(when, then):
        out.append(
            f"      assertTrue(\"route '{op}' declared in when was never hit "
            f"(${{rec.countFor({_kt_str(op)})}} requests)\", "
            f"rec.countFor({_kt_str(op)}) > 0)"
        )
    for op in _row_not_called(then):
        out.append(
            f"      assertEquals(\"{not_called_message(op)} "
            f"${{rec.countFor({_kt_str(op)})}} time(s)\", 0, rec.countFor({_kt_str(op)}))"
        )
    allowed = ", ".join(_kt_str(op) for op in row.allowed_ops)
    out.append(
        f"      assertEquals({_kt_str(UNEXPECTED_OPS_MESSAGE)}, emptyList<String>(), "
        f"rec.unexpectedOps(setOf<String>({allowed})))"
    )
    red, gate = unmatched_gate()
    if red:
        out.append(f"      assertEquals({_kt_str(unmatched_message('android'))}, emptyList<String>(), "
                   "rec.unmatchedCalls())")
    else:
        out.append(f"      reportUnmatched(rec.unmatchedCalls(), {_kt_str(gate) if gate else 'null'}, "
                   f"{_kt_str(_notice_row(screen, method_name, contract, row))})")

    for key, value in then.items():
        if key == "api":
            out.append("      assertTrue(\"expected no declared-API calls, got ${rec.matchedCalls()}\", rec.matchedCalls().isEmpty())")
        elif key == "transition":
            out.append(f"      h.expectTransition({_kt_str(value)})")
        elif key.startswith("api.") and key.endswith(".request"):
            op = key[len("api."):-len(".request")]
            out.append(f"      assertTrue(rec.countFor({_kt_str(op)}) > 0)")
            out.append(
                f"      assertEquals(emptyList<String>(), "
                f"partialMismatches(rec.lastBodyFor({_kt_str(op)}), {_kt_expected(value)}))"
            )
        elif key.startswith("api."):
            op = key[len("api."):]
            if value == "called":
                out.append(f"      assertTrue(rec.countFor({_kt_str(op)}) > 0)")
            # not-called: asserted before the bound (`_row_not_called`)
        elif key.startswith("data."):
            fname = key[len("data."):]
            head, *tail = fname.split(".")
            if tail:
                out.append(
                    f"      assertEquals(emptyList<String>(), valueMismatches("
                    f"h.readField({_kt_str(head)}), "
                    f"{_kt_expected(_nested_expectation(tail, value))}))"
                )
            else:
                out.append(
                    f"      assertFieldEquals({_kt_expected(value)}, "
                    f"h.readField({_kt_str(fname)}))"
                )
    if row.control_of:
        # P2e(b): see the web emitter. An assertion throws, so a caught one
        # means the row does not hold with the defaults.
        body = ["  " + line for line in out[act_start:]]
        out[act_start:] = (["      val holds = try {"] + body
                           + ["        true", "      } catch (e: Throwable) {", "        false", "      }",
                              f"      reportConditionWithoutEffect(holds, "
                              f"{_kt_str(_notice_row(screen, method_name, contract, row))}, "
                              f"{_kt_str(_control_label(row))})"])
    out.append("    }")
    out.append("  }")
    return out


