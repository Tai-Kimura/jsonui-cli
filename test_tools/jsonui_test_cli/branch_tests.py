@dataclass
class GenerationReport:
    screen: str
    test_file: Path | None = None
    runtime_file: Path | None = None
    harness_file: Path | None = None
    harness_created: bool = False
    harness_absent: bool = False
    #: The app's one `arrangeCondition` hook file (consumer-owned), when the
    #: app declares `harnessConditions`; None otherwise.
    conditions_hook_file: Path | None = None
    conditions_hook_created: bool = False
    #: check mode: the app declares conditions and the hook file is missing.
    conditions_hook_absent: bool = False
    #: An EXISTING consumer harness predating `invoke` on this platform.
    #: The harness is consumer-owned and never overwritten, so shipping the
    #: fix does not reach the projects that hit the defect — the population
    #: it does not reach has to be named by the tool rather than left to a
    #: release note nobody re-reads. Never a failure: it is their file.
    harness_lacks_invoke: bool = False
    declared_branches: int = 0
    note_branches: int = 0
    platform_skipped: int = 0
    #: Generated tests that are `alsoStatuses` copies (not in declared_branches).
    also_statuses_rows: int = 0
    #: P2e(b): condition controls emitted (only with `--condition-controls`).
    condition_controls: int = 0
    #: True when the platform is outside the screen's effective platforms
    #: (`jui.config.json` platforms ∩ `metadata.platforms`).
    platform_excluded: bool = False
    #: Printed lines naming route pairs one request could match, and the winner.
    route_overlaps: list = field(default_factory=list)
    methods: list[str] = field(default_factory=list)
    routes: list[str] = field(default_factory=list)
    #: The side routes among `routes` (P2e(d)); printed only when there are any.
    side_routes: list[str] = field(default_factory=list)
    #: False when the screen declares contracts but none of its branches
    #: apply to this platform. Nothing is emitted and nothing is expected:
    #: a test file holding no assertion is the "column that did not run",
    #: and the convention for those is not to print them.
    platform_applicable: bool = True
    #: Generated files retired because this screen no longer produces them
    #: on this platform (in check mode: that are still on disk).
    stale: list[Path] = field(default_factory=list)
    #: Files where a generated one would be, without this tool's banner.
    unowned: list[Path] = field(default_factory=list)
    #: check mode only — @generated files whose bytes differ / are missing.
    drifted: list[Path] = field(default_factory=list)
    absent: list[Path] = field(default_factory=list)
    matched: list[Path] = field(default_factory=list)

    @property
    def up_to_date(self) -> bool:
        return not self.drifted and not self.absent


@dataclass
class _Emitter:
    """Writes the generated files, or compares them to what is on disk.

    Two properties this exists to hold:

    - **Check mode does not touch the tree.** No mkdir, no write. A check
      that creates the directory it is auditing reports "0 drifted" on a
      project that has never generated anything, and leaves an empty
      directory behind to make the second run agree with it.
    - **The bytes compared are the bytes that would be written.** The
      content is produced by the same expression in both modes rather than
      re-rendered for the comparison, so a check cannot pass against a
      rendering path the writer does not use.
    """

    check: bool = False
    drifted: list[Path] = field(default_factory=list)
    absent: list[Path] = field(default_factory=list)
    matched: list[Path] = field(default_factory=list)
    #: Generated files deleted (or, in check mode, that would be) because
    #: the screen no longer produces them on this platform.
    stale: list[Path] = field(default_factory=list)
    #: Files sitting where a generated one would be that this tool does not
    #: own. Never touched, always reported — the only safe answer when the
    #: ownership marker is missing is to say so.
    unowned: list[Path] = field(default_factory=list)

    def mkdir(self, path: Path) -> None:
        if not self.check:
            path.mkdir(parents=True, exist_ok=True)

    def emit(self, path: Path, content: str) -> None:
        if not self.check:
            path.write_text(content, encoding="utf-8")
            return
        if not path.exists():
            self.absent.append(path)
            return
        try:
            current = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            self.drifted.append(path)
            return
        (self.matched if current == content else self.drifted).append(path)

    def retire(self, path: Path) -> None:
        """Delete a file this generator wrote and no longer produces.

        The generator only ever wrote, so a screen that stops producing a
        test left its last one on disk running the old contract. Reported as
        skipped by the run that stopped producing it, and reported by no
        gate at all: `--check` does not count a screen that is not
        applicable to this platform, so neither direction of the failure was
        visible. Both directions are bad and the quiet one is worse — a
        leftover that still passes reads as "this screen has branch tests
        for this platform", about a screen that has none.

        Ownership is CHECKED, not inferred from the path. A file is deleted
        only if it carries the `@generated` banner this tool writes, so the
        hand-written harness beside it — same directory, same naming
        convention — cannot be caught by a bug in how the name was built.
        Anything else is left alone and reported instead.

        Check mode deletes nothing, for the reason mkdir does nothing: a
        check that changes the tree it is auditing agrees with itself on the
        second run.
        """
        if not path.exists():
            return
        try:
            head = path.read_text(encoding="utf-8")[:400]
        except (OSError, UnicodeDecodeError):
            self.unowned.append(path)
            return
        if GENERATED_MARKER not in head:
            self.unowned.append(path)
            return
        self.stale.append(path)
        if not self.check:
            path.unlink()

    def apply_to(self, report: "GenerationReport") -> None:
        report.drifted = list(self.drifted)
        report.absent = list(self.absent)
        report.matched = list(self.matched)
        report.stale = list(self.stale)
        report.unowned = list(self.unowned)


def _branch_active(branch: dict, platform: str) -> bool:
    """Platform-scoped branches (branch['platforms']) render only on their
    listed platforms; unscoped branches render everywhere."""
    platforms = branch.get("platforms")
    if not isinstance(platforms, list) or not platforms:
        return True
    return platform in platforms


def _iter_declared_api_refs(contract: dict):
    """Yield (op, scenario_or_None, where, branch_index) for every api.* reference."""
    for i, branch in enumerate(contract.get("branches") or []):
        if not isinstance(branch, dict) or "note" in branch:
            continue
        for key, value in (branch.get("when") or {}).items():
            if key.startswith("api."):
                yield key[len("api."):], value, f"branches[{i}].when.{key}", i
        for key, _value in (branch.get("then") or {}).items():
            if key == "api" or not key.startswith("api."):
                continue
            rest = key[len("api."):]
            op = rest[: -len(".request")] if rest.endswith(".request") else rest
            yield op, None, f"branches[{i}].then.{key}", i


def _side_call_ref_error(op: str, where: str, contract: dict, index: int,
                         mock: MockFile, ops) -> str | None:
    """Why a row cannot name the side call ``op`` the way it does, or None.

    A rule's `sideCalls` operation that this screen does not declare can be
    written in a row only as ``then "api.<op>": "not-called"`` — the one
    thing a screen row can pin about the network layer's call (the opt-out
    flag that must keep it from happening). Not "called": a row's "called"
    permits an op in every row of its method, which would widen the rule's
    statuses, and the call itself is the rule's `verifiedBy` unit case's to
    assert. Not in `when` or as `.request`: a side route is served with its
    mock's default scenario, which no row chooses, and its request is the
    network layer's. And not under the operationId when the screen declares
    the same endpoint under its own name: the side route is not added then,
    so a count under the operationId would always read 0.
    """
    from .mock.generate import route_key

    identity = route_key(mock.method, mock.path)
    for name, endpoint in ops.canonical.items():
        if route_key(endpoint["method"], endpoint["path"]) == identity:
            return (f"{where}: '{op}' is {mock.method} {mock.path}, which this screen "
                    f"declares as '{name}' — write api.{name}")
    reason = None
    if ".when." in where:
        reason = ("a side route is served with its mock's default scenario, which "
                  "no row chooses")
    elif where.endswith(".request"):
        reason = "its request is the network layer's; the rule's verifiedBy unit case asserts it"
    else:
        branch = (contract.get("branches") or [])[index]
        value = (branch.get("then") or {}).get(f"api.{op}")
        if value == "called":
            reason = ("a row's \"called\" permits the op in every row of its method, "
                      "which would widen the rule's statuses; the rule's verifiedBy unit "
                      "case asserts the call")
    if reason is None:
        return None
    return (f"{where}: '{op}' is an apiOutcomeRules sideCalls operation this screen "
            f"does not declare — a row can only say it is \"not-called\" ({reason})")


def _scenario_body(scenario: dict) -> str:
    """Response body serialized the way the project's mock server serializes it.

    The rule is `mock/server.py`'s `_send`: a `dict`/`list` is JSON-encoded,
    a `str` is written verbatim, and an absent body sends no payload. This
    function is what the generated Kotlin/Swift tests embed, so a rule that
    differs from the server makes the SAME mock file behave differently
    under `mock serve` than under the generated tests.

    A `str` body must not be JSON-encoded. Encoding it wrapped the payload
    in quotes and turned every newline into `\n`, so an NDJSON or SSE
    stream arrived as a single quoted line: the app's line parser saw no
    records and took its error path, under EVERY scenario including the
    default. The UI tests, which go through the mock server, kept passing.

    A file-backed response (`contentType` + `bodyFile`) has no inline body.
    Serializing the absent value produced the literal `null`, which is a
    body the server never sends — the server answers with an empty payload
    and the declared content type, so this matches it. An explicit
    `"body": null` takes the same path for the same reason (`server.py`
    sends `b""` for either).
    """
    body = scenario.get("body")
    if body is None:
        return ""
    if isinstance(body, str):
        return body
    return json.dumps(body, ensure_ascii=False)


#: `mock serve` sleeps `min(delayMs, 30000)`; the runtimes cap it the same.
DELAY_CAP_MS = 30000


def _scenario_delay_ms(scenario: dict) -> int:
    """A scenario's `delayMs` as the runtimes apply it: whole milliseconds,
    0 when absent or not a positive number, at most DELAY_CAP_MS. The web
    runtime reads the scenario itself (the routes carry it whole); the
    mobile routes carry this, and only for a route that has one."""
    value = scenario.get("delayMs") if isinstance(scenario, dict) else None
    if isinstance(value, bool) or not isinstance(value, (int, float)) or value <= 0:
        return 0
    return int(min(value, DELAY_CAP_MS))


def _scenario_content_type(scenario: dict) -> str:
    value = scenario.get("contentType")
    return value if isinstance(value, str) and value else "application/json"


def _mocks_dir_label(mocks_dir: Path | None) -> str:
    """Absolute path when known — "the mocks directory" told an author the
    file was missing when it existed somewhere the search never looked."""
    if mocks_dir is None:
        return "the mocks directory"
    return str(mocks_dir)


def resolve_routes(
    spec: dict, methods_contracts: dict, mocks: list[MockFile],
    mocks_dir: Path | None = None, errors: list | None = None,
    side_calls: dict | None = None,
) -> list[Route]:
    """Bind every referenced api.<op> (plus every declared endpoint with a
    mock, so incidental calls get their default scenario) to a Route.

    ``side_calls`` (operationId -> its one generated mock, from the rules'
    `sideCalls`): a row may say such an operation was NOT called without the
    screen declaring it — its route is the side route `side_routes` adds.
    Only "not-called": see `_side_call_ref_error`.

    Unbindable references raise — a branch whose scenario cannot be found
    must fail generation, not soften into a weaker test. Given an ``errors``
    list, each unbindable reference is appended to it as a `BindingError`
    instead, and binding goes on: `contracts coverage` needs every row that
    CAN be judged, not the first one that cannot.
    """
    from .mock.generate import route_key, route_match_order

    ops = collect_endpoint_ops(spec)
    routes: dict[str, Route] = {}
    # Which op string already owns an endpoint, so the same endpoint cannot
    # end up behind two spellings. `countFor` matches recorded calls by op
    # string, and only the first matching route records — so a second route
    # over the same path would make every assert under the other spelling
    # count zero. A contract that is written but never checked is the failure
    # this whole ticket is about, so mixing spellings is refused outright.
    # Keyed by `route_key`, so two spellings of one path template
    # (`/items/{id}` and `/items/{item_id}`) are the one endpoint they are.
    endpoint_owner: dict[tuple, str] = {}

    def bind(op: str, where: str) -> Route:
        if op in routes:
            return routes[op]
        if op in ops.collisions:
            raise BranchTestGenerationError(
                f"{where}: api operation '{op}' is declared by "
                f"{' and '.join(ops.collisions[op])} — the bare name does not "
                "say which endpoint the contract means. Qualify it, e.g. "
                f"'api.{ops.collisions[op][0]}'"
            )
        canonical = ops.resolve(op)
        if canonical is None:
            raise BranchTestGenerationError(
                f"{where}: api operation '{op}' has no `endpoint` declaration in "
                "dataFlow.repositories/useCases — declare the method with its "
                "endpoint (e.g. \"endpoint\": \"POST /api/...\"), or, for a call the "
                "app's network layer makes, name its operationId in an "
                "apiOutcomeRules sideCalls and say \"not-called\""
            )
        endpoint = ops.canonical[canonical]
        identity = route_key(endpoint["method"], endpoint["path"])
        if identity in endpoint_owner and endpoint_owner[identity] != op:
            raise BranchTestGenerationError(
                f"{where}: api operation '{op}' and "
                f"'{endpoint_owner[identity]}' both name {endpoint['method']} "
                f"{endpoint['path']} — refer to one endpoint by one name, or "
                "only the first spelling will match recorded calls"
            )
        mock = find_mock(mocks, endpoint["method"], endpoint["path"])
        if mock is None:
            raise BranchTestGenerationError(
                f"{where}: no mock file found for {endpoint['method']} "
                f"{endpoint['path']} (op '{op}') — searched "
                f"{_mocks_dir_label(mocks_dir)} and found "
                f"{len(mocks)} mock file(s)"
            )
        endpoint_owner[identity] = op
        route = Route(
            op=op, method=endpoint["method"], path=endpoint["path"],
            pattern=path_to_pattern(endpoint["path"]),
            scenarios=mock.scenarios, default_scenario=mock.active_scenario,
        )
        routes[op] = route
        return route

    for method_name, contract in methods_contracts.items():
        if not isinstance(contract, dict):
            continue
        for op, scenario, where, index in _iter_declared_api_refs(contract):
            try:
                if side_calls and op in side_calls and ops.resolve(op) is None \
                        and op not in ops.collisions:
                    problem = _side_call_ref_error(
                        op, where, contract, index, side_calls[op], ops)
                    if problem:
                        raise BranchTestGenerationError(problem)
                    continue        # served by its side route
                route = bind(op, where)
                if scenario is not None and scenario not in route.scenarios:
                    raise BranchTestGenerationError(
                        f"{where}: scenario '{scenario}' not found in "
                        f"{sorted(route.scenarios)} (mock for {route.method} {route.path})"
                    )
            except BranchTestGenerationError as e:
                if errors is None:
                    raise
                errors.append(BindingError(method_name, index, op, None, str(e)))

    # Every other declared endpoint that has a mock file joins with its
    # default scenario, so incidental calls during act don't 599. Keyed by
    # ENDPOINT, not by op string: an endpoint already bound under its bare
    # name would otherwise be added a second time under its canonical one.
    for op, endpoint in ops.canonical.items():
        identity = route_key(endpoint["method"], endpoint["path"])
        if identity in endpoint_owner:
            continue
        mock = find_mock(mocks, endpoint["method"], endpoint["path"])
        if mock is not None:
            endpoint_owner[identity] = op
            routes[op] = Route(
                op=op, method=endpoint["method"], path=endpoint["path"],
                pattern=path_to_pattern(endpoint["path"]),
                scenarios=mock.scenarios, default_scenario=mock.active_scenario,
            )
    # The order `mock serve` tries routes in (static paths first), so a call
    # both could match is recorded under the op whose mock answers it.
    return sorted(routes.values(), key=lambda route: route_match_order(route.path))


def route_overlaps(routes: list[Route]) -> list[tuple[Route, Route]]:
    """Pairs of routes one request could match, as (the one that wins, the other).

    Routes are tried in `route_match_order` — the order `mock serve` uses — and
    a call is recorded under the first that matches, so for
    `GET /items/export` beside `GET /items/{item_id}` an export is recorded as
    the export op, served by its mock, exactly as `mock serve` would. Not an
    error: printed, so the pair and the side that wins are never silent.

    Two paths overlap when the method is the same, the segment count is the
    same, and every pair of segments is the same literal or has a `{param}` on
    at least one side. (Two SPELLINGS of one template are refused earlier.)
    """
    from .mock.generate import route_match_order

    def segments(path: str) -> list[str]:
        return [seg for seg in path.strip("/").split("/")]

    def is_param(seg: str) -> bool:
        return seg.startswith("{") and seg.endswith("}")

    ordered = sorted(routes, key=lambda route: route_match_order(route.path))
    pairs = []
    for i, a in enumerate(ordered):
        for b in ordered[i + 1:]:
            if a.method != b.method:
                continue
            sa, sb = segments(a.path), segments(b.path)
            if len(sa) != len(sb):
                continue
            if all(x == y or is_param(x) or is_param(y) for x, y in zip(sa, sb)):
                pairs.append((a, b))
    return pairs


def describe_overlap(winner: Route, other: Route) -> str:
    return (f"route overlap: {winner.method} {winner.path} ('{winner.op}') and "
            f"{other.path} ('{other.op}') — a call both match is recorded as "
            f"'{winner.op}' (the order mock serve uses)")


RESPONSE_REF_PREFIX = "@response."


def resolve_response_refs(methods_contracts: dict, routes: list[Route]) -> None:
    """Replace `@response.<path>` in `then` with the value the branch's own
    scenario actually returns, in place.

    Some screens display a string the server chose — an API error message
    passed through to an alert. The contract cannot spell it as a literal
    (it is not ours) nor as a strings key (it is not in the table), so those
    branches were being written as prose notes and going untested. What the
    contract *can* say is "this field shows what the server sent", and since
    the branch already names the scenario, the expected text is knowable
    here: read it out of the mock and hand the renderers a literal.

    Resolution failures raise. A reference that cannot be bound is a broken
    declaration, and quietly asserting something weaker would leave the
    branch looking covered.
    """
    by_op = {route.op: route for route in routes}

    for method_name, contract in methods_contracts.items():
        if not isinstance(contract, dict):
            continue
        for i, branch in enumerate(contract.get("branches") or []):
            if not isinstance(branch, dict) or "note" in branch:
                continue
            _resolve_branch_response_refs(
                branch, by_op, f"methods.{method_name}.branches[{i}]")


def _resolve_branch_response_refs(branch: dict, by_op: dict, where: str) -> None:
    """`resolve_response_refs` for one branch (in place). Raises on failure."""
    then = branch.get("then")
    if not isinstance(then, dict):
        return
    refs = [
        (k, v) for k, v in then.items()
        if isinstance(v, str) and v.startswith(RESPONSE_REF_PREFIX)
    ]
    if not refs:
        return
    scenarios = {
        k[len("api."):]: v
        for k, v in (branch.get("when") or {}).items()
        if k.startswith("api.") and isinstance(v, str)
    }
    if len(scenarios) != 1:
        raise BranchTestGenerationError(
            f"{where}: '@response.<path>' needs exactly one "
            f"`api.<op>` in `when` to read the response from, found "
            f"{len(scenarios)}"
        )
    op, scenario_name = next(iter(scenarios.items()))
    route = by_op.get(op)
    if route is None:
        raise BranchTestGenerationError(
            f"{where}: no route bound for api operation '{op}'"
        )
    scenario = route.scenarios.get(scenario_name)
    if not isinstance(scenario, dict):
        raise BranchTestGenerationError(
            f"{where}: scenario '{scenario_name}' of '{op}' is not an "
            "object, so it has no response body to read"
        )
    body = scenario.get("body")
    for key, ref in refs:
        path = ref[len(RESPONSE_REF_PREFIX):]
        then[key] = _read_response_path(body, path, where, key, scenario_name)


def _read_response_path(body, path: str, where: str, key: str, scenario: str):
    """The value at `path` in a scenario's response body.

    Lists are indexed by a dotted number: `detail.0.msg`. ONE spelling, not
    two — `detail[0].msg` was offered as an alternative by the lane that
    asked for this and is refused by name instead, because the rest of this
    vocabulary is dotted (`@data.<field>`, the `then` keys) and a second
    spelling is a second thing every reader of a contract has to know.
    A path that uses brackets is told which form to write.

    The shape this exists for is FastAPI's 422: the text a screen shows is
    always inside `detail[]`, so a contract could not say "the screen shows
    what the server sent" about the one response class where that claim is
    most worth making. The reporting lane fell back to a literal
    expectation, which still discriminates but binds the contract to the
    mock body — the thing `@response.` was introduced to avoid.
    """
    if not path:
        raise BranchTestGenerationError(
            f"{where}.then.{key}: '@response.' needs a field path "
            "(e.g. '@response.error.message')"
        )
    parts = path.split(".")
    node = body
    walked: list[str] = []
    for position, part in enumerate(parts):
        at = ".".join(walked) or "(root)"
        if "[" in part or "]" in part:
            # Named before the lookup fails, because the lookup would fail
            # with "no such key", which is true and unhelpful.
            raise BranchTestGenerationError(
                f"{where}.then.{key}: '{path}' indexes with brackets; write "
                f"the position as a dotted number instead — "
                f"'{path.replace('[', '.').replace(']', '')}'"
            )
        if isinstance(node, list):
            if not part.isdigit():
                # The message the reporting lane asked for. Falling through
                # to the object branch printed "the available keys are: (not
                # an object)", which reads as "there are no candidates" when
                # what it means is "you are standing on a list".
                suggestion = ".".join(walked + ["0"] + parts[position:])
                raise BranchTestGenerationError(
                    f"{where}.then.{key}: scenario '{scenario}' has a list of "
                    f"{len(node)} item(s) at {at} in its response body, not an "
                    f"object — index it by position: '{suggestion}'"
                )
            index = int(part)
            if index >= len(node):
                raise BranchTestGenerationError(
                    f"{where}.then.{key}: scenario '{scenario}' has "
                    f"{len(node)} item(s) at {at} in its response body, so "
                    f"index {index} in '{path}' is past the end"
                )
            node = node[index]
        elif isinstance(node, dict):
            if part not in node:
                raise BranchTestGenerationError(
                    f"{where}.then.{key}: scenario '{scenario}' has no "
                    f"'{path}' in its response body — at {at} the available "
                    f"keys are: {', '.join(sorted(node))}"
                )
            node = node[part]
        else:
            raise BranchTestGenerationError(
                f"{where}.then.{key}: scenario '{scenario}' has a "
                f"{type(node).__name__} at {at} in its response body, so "
                f"'{path}' cannot be read past there"
            )
        walked.append(part)
    if isinstance(node, (dict, list)):
        raise BranchTestGenerationError(
            f"{where}.then.{key}: '{path}' in scenario '{scenario}' is a "
            f"{type(node).__name__}, and a displayed value must be a scalar"
        )
    return node


def method_params(spec: dict, method_name: str) -> list[str]:
    view_model = (spec.get("dataFlow") or {}).get("viewModel") or {}
    for method in view_model.get("methods", []) or []:
        if isinstance(method, dict) and method.get("name") == method_name:
            params = method.get("params")
            if isinstance(params, list):
                return [p.get("name") for p in params
                        if isinstance(p, dict) and isinstance(p.get("name"), str)]
            return []
    return []


def _method_is_declared(spec: dict, method_name: str) -> bool:
    view_model = (spec.get("dataFlow") or {}).get("viewModel") or {}
    for method in view_model.get("methods", []) or []:
        if isinstance(method, dict) and method.get("name") == method_name:
            return True
        if isinstance(method, str) and method.split("(")[0].strip() == method_name:
            return True
    return False


def check_arg_bindings(spec: dict, methods_contracts: dict,
                       errors: list | None = None) -> None:
    """Every `arg.<name>` has to name a declared parameter.

    The act call is built from `dataFlow.viewModel.methods[].params`, so an
    `arg` that matches nothing there used to be dropped on the floor: the
    method was invoked with no arguments and the branch passed or failed for
    reasons unrelated to what it declared. A harness with a closed switch
    notices (it receives nil); a lenient one substitutes a default and stays
    green while testing a different case than the contract describes.

    eventHandlers are not an alternative declaration site. They are
    View-layer handlers by design and carry no signature, which is why
    adding params there changes nothing — a method whose arguments a
    contract wants to pin belongs in the ViewModel's public API.
    """
    for method_name, contract in methods_contracts.items():
        if not isinstance(contract, dict):
            continue
        params = set(method_params(spec, method_name))
        declared = _method_is_declared(spec, method_name)
        for i, branch in enumerate(contract.get("branches") or []):
            if not isinstance(branch, dict) or "note" in branch:
                continue
            for key in (branch.get("when") or {}):
                if not key.startswith("arg."):
                    continue
                name = key[len("arg."):]
                if name in params:
                    continue
                where = f"methods.{method_name}.branches[{i}].when.{key}"
                if not declared:
                    message = (
                        f"{where}: '{method_name}' is not declared in "
                        "dataFlow.viewModel.methods, so it has no parameter "
                        "list to bind this argument to — declare it there "
                        "with `params` (stateManagement.eventHandlers is "
                        "View-layer only and carries no signature)"
                    )
                else:
                    message = (
                        f"{where}: '{method_name}' declares no parameter "
                        f"'{name}' — its params are "
                        f"{sorted(params) if params else '(none)'}"
                    )
                if errors is None:
                    raise BranchTestGenerationError(message)
                errors.append(BindingError(method_name, i, None, None, message))


