def load_project_config(project_root: Path) -> dict:
    for name in ("jui.config.json", "jsonui-test.config.json"):
        p = project_root / name
        if p.exists():
            try:
                with open(p, "r", encoding="utf-8") as f:
                    return json.load(f)
            except (OSError, json.JSONDecodeError):
                pass
    return {}


PARENT_SPEC_TYPE = "screen_parent_spec"

#: A declaration site that belongs to no single screen. Spelled here because
#: `jsonui-doc`'s validator accepts the same literal: two packages that
#: disagree about this string would make an app spec validate as a document
#: and stay invisible to the gate, which is silence rather than an error.
#: The paired test reads `jsonui_doc_cli`'s constant and compares.
APP_CONTRACTS_SPEC_TYPE = "app_contracts_spec"

#: The app's one harness-condition hook, per platform (design v4.11, P2d):
#: consumer-owned, in the harness directory, one per APP — the conditions are
#: declared once in the app contracts spec, the hook runs before any screen's
#: harness exists (so it cannot be a harness method), and Kotlin/Swift screen
#: harnesses share one package/module, where a top-level function per screen
#: would collide.
WEB_CONDITIONS_MODULE = "branch-conditions"
KOTLIN_CONDITIONS_FILE = "BranchConditions.kt"
SWIFT_CONDITIONS_FILE = "BranchConditions.swift"

#: The substring every banner this generator writes contains. Ownership is
#: read from the FILE rather than assumed from its path, so a mistake in
#: building a filename cannot reach a hand-written harness.
GENERATED_MARKER = "@generated by `jsonui-test generate branch-tests"


def _prefer_sibling_jui_cli() -> None:
    """Put the jui_cli from THIS tree ahead of any separately installed one.

    Same bootstrap `validation/screen_ids.py` uses. jsonui-test ships
    separately from jui but always sits beside it, and without this the
    import resolves to the distributed copy — which is the right answer at
    runtime and the wrong one under test.
    """
    sibling = Path(__file__).resolve().parents[2] / "jui_tools"
    if not (sibling / "jui_cli" / "core" / "parent_spec_merger.py").is_file():
        return
    if str(sibling) not in sys.path:
        sys.path.insert(0, str(sibling))
    cached = sys.modules.get("jui_cli")
    cached_file = str(getattr(cached, "__file__", "") or "")
    if cached is not None and not cached_file.startswith(str(sibling)):
        for name in [n for n in sys.modules
                     if n == "jui_cli" or n.startswith("jui_cli.")]:
            del sys.modules[name]


def _merge_parent_spec(parent_path: Path) -> dict | None:
    """The merged view of a parent spec and the sub-specs it declares.

    Delegated to `jui_cli.core.parent_spec_merger`, which is what `jui
    build` and `jui verify` already use to read a split screen: parent plus
    sub-specs is ONE screen producing one layout and one view model.
    Answering that question differently here is how this tool came to treat
    sibling sub-specs as strangers, so a contract in one of them could not
    see the endpoint declared in another.

    The family is the parent's `subSpecs` DECLARATION, not the directory
    listing — sitting in the same folder is not membership, and the
    declaration is the only thing that says what belongs together.

    Returns None when jui_cli is unavailable (a tool tree synced without
    it): a split project then behaves as it did before, which is the
    failure this removes rather than a new one.
    """
    return _merge_parent_spec_result(parent_path)[0]


def _merge_parent_spec_result(parent_path: Path) -> tuple[dict | None, str | None]:
    """``(merged spec, refusal)`` — the two ways a merge can produce nothing.

    They used to be the same value. `merge_from_file` raises on a parent that
    declares a section the merger builds from the sub-specs, and that refusal
    was swallowed into the same `None` a tool tree WITHOUT jui_cli returns.
    `_load_spec` then fell back to the raw parent — handing the caller the
    very block the exception was about, so the declaration counted as read
    while the merger had refused it and the generated code kept the
    sub-specs' view. Measured 2026-09-07: a parent declaring `unitContracts`
    reported `declared 4, missing 0, undeclared 0` and exit 0, on the same
    tree where `jui verify` exits 1 with the message raised right here.

    So the refusal is returned instead of dropped, IN THE MERGER'S OWN WORDS.
    Not re-authored here: a second wording of one rule is a second rule, and
    this one is already stated once, in `shared/core/parent_spec_rules.py`,
    which is what `jui verify` prints.

    `(None, None)` still means "no merger in this tree" — a real state, and
    the only one the old return value was entitled to mean.
    """
    _prefer_sibling_jui_cli()
    try:
        from jui_cli.core.parent_spec_merger import ParentSpecMerger
    except ImportError:
        return None, None
    try:
        return ParentSpecMerger(spec_dir=parent_path.parent).merge_from_file(
            parent_path).spec, None
    except ValueError as e:
        # A declaration the parent may not carry. `jui build` reports this in
        # its own run; a read-only caller needs to know its input was refused,
        # because the fallback below is about to give it that input anyway.
        return None, str(e)
    except (OSError, KeyError, json.JSONDecodeError):
        return None, None


def _load_spec(spec_file: Path) -> dict:
    """The spec as this generator should read it — merged when it is a parent."""
    return _load_spec_result(spec_file)[0]


def _load_spec_result(spec_file: Path) -> tuple[dict, str | None]:
    """``(spec, refusal)`` — the spec as read, and why it is not the merged one.

    A refusal means the returned dict is the RAW parent, including whatever
    the merger declined. Callers that count declarations must report it:
    counting a refused block reads as "the declaration was checked".
    """
    with open(spec_file, "r", encoding="utf-8") as f:
        spec = json.load(f)
    if spec.get("type") == PARENT_SPEC_TYPE:
        merged, refusal = _merge_parent_spec_result(spec_file)
        if merged is not None:
            return merged, None
        return spec, refusal
    return spec, None


def _parent_declaring(path: Path, spec_path: Path) -> Path | None:
    """The parent under *spec_path* that declares *path* in its subSpecs.

    A sub-spec is not a screen of its own: it is part of one. Listing it
    separately is what made a whole-project run try to generate half a
    screen and fail on the half it could not see.
    """
    for candidate in _spec_files(spec_path):
        try:
            with open(candidate, "r", encoding="utf-8") as f:
                parent = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        if parent.get("type") != PARENT_SPEC_TYPE:
            continue
        for entry in parent.get("subSpecs") or []:
            if not isinstance(entry, dict):
                continue
            ref = entry.get("file")
            if not ref:
                continue
            for base in (candidate.parent, spec_path):
                if (base / ref).resolve() == path.resolve():
                    return candidate
    return None


def _is_sub_spec_of_a_parent(path: Path, spec_path: Path) -> bool:
    return _parent_declaring(path, spec_path) is not None


def _parent_of_sub_spec(spec_file: Path, project_root: Path) -> Path | None:
    """The parent owning *spec_file*, when the project declares one."""
    config = load_project_config(project_root)
    spec_dir = config.get("spec_directory")
    if not spec_dir:
        return None
    spec_path = (project_root / spec_dir).resolve()
    if not spec_path.is_dir():
        return None
    return _parent_declaring(spec_file, spec_path)


def sub_spec_screen_names(project_root: Path,
                          spec_dir: str | None = None) -> list[str]:
    """Screen names that are sub-specs — parts of a screen, not screens.

    Used to explain a check result rather than to decide one. When a project
    upgrades across the change that made parent+subSpecs ONE screen, its
    generated directory still holds a file per sub-spec and none for the
    parent, and the check reports the parent as `[ABSENT]` while saying
    nothing about the files that are now orphans. A consumer read that as a
    generation failure and worked backwards from an unrelated import error
    before reaching the model change; several steps, all of them spent
    finding out what the red meant.
    """
    if spec_dir is None:
        spec_dir = load_project_config(project_root).get("spec_directory")
    if not spec_dir:
        return []
    spec_path = (project_root / spec_dir).resolve()
    if not spec_path.is_dir():
        return []
    names: list[str] = []
    for path in _spec_files(spec_path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                raw = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        if raw.get("type") == PARENT_SPEC_TYPE:
            continue
        if _is_sub_spec_of_a_parent(path, spec_path):
            names.append(_screen_of(path))
    return names


#: What a generated artefact is called, per platform, given a screen name.
#: Only used to spot the leftovers from the old one-file-per-sub-spec
#: layout, so a miss here costs an explanation, never a verdict.
_ARTEFACT_PATTERNS = {
    "web": ("{screen}.branches.test.ts",),
    "android": ("{screen}BranchTest.kt", "{screen}BranchTests.kt"),
    "ios": ("{screen}BranchTests.swift",),
}


def orphaned_sub_spec_artefacts(project_root: Path, out_dir: str,
                                platform: str = "web",
                                spec_dir: str | None = None) -> list[Path]:
    """Generated files named after a sub-spec, which no longer generates one."""
    names = sub_spec_screen_names(project_root, spec_dir)
    if not names:
        return []
    out_path = (project_root / out_dir).resolve()
    if not out_path.is_dir():
        return []
    found: list[Path] = []
    for name in names:
        for pattern in _ARTEFACT_PATTERNS.get(platform, ()):
            for path in out_path.rglob(pattern.format(screen=name)):
                found.append(path)
    return sorted(set(found))


def _spec_files(spec_path: Path) -> list[Path]:
    """Every spec under *spec_path*, at any depth.

    Splitting a parent spec puts its screens in `<spec_directory>/<parent>/`,
    which a non-recursive lookup cannot see. `@generated` files may not be
    hand-edited, so a screen the generator cannot resolve is a screen whose
    tests can never be updated again.
    """
    return sorted(spec_path.rglob("*.spec.json"))


def _screen_of(path: Path) -> str:
    return path.name[: -len(".spec.json")]


def resolve_spec_path(screen: str, project_root: Path, explicit: str | None) -> Path:
    if explicit:
        return (project_root / explicit).resolve() if not Path(explicit).is_absolute() else Path(explicit)
    config = load_project_config(project_root)
    spec_dir = config.get("spec_directory")
    if not spec_dir:
        raise BranchTestGenerationError(
            "spec_directory is not declared in jui.config.json and --spec was not given"
        )
    spec_path = (project_root / spec_dir).resolve()
    flat = spec_path / f"{screen}.spec.json"
    if flat.exists():
        return flat
    # Same rule as the canonical `screen_id_for_path`: the basename is the
    # identity and the directories above it are not part of it.
    matches = [p for p in _spec_files(spec_path) if _screen_of(p) == screen]
    if len(matches) == 1:
        return matches[0]
    if len(matches) > 1:
        # Choosing by sort order is how a route silently collapses onto one
        # file; two screens with one id is the project's to resolve.
        listed = ", ".join(str(p.relative_to(spec_path)) for p in matches)
        raise BranchTestGenerationError(
            f"'{screen}' matches {len(matches)} specs ({listed}) — the "
            "basename is the screen id, so these are the same screen twice; "
            "rename one or pass --spec"
        )
    return flat


def discover_branch_screens(
    project_root: Path, spec_dir: str | None = None,
) -> tuple[list[str], list[str], list[str]]:
    """``(screens declaring branchContracts.methods, every spec scanned, problems)``.

    Both halves are returned because the caller has to name a denominator.
    "0 drifted" over an empty scan and "0 drifted" over nine screens are the
    same sentence and opposite facts, and the unit of regeneration here is
    the project rather than the screen — the runtime is one file the whole
    directory shares, so a release that changes its shape leaves every
    screen that was not regenerated pointing at the old one.
    """
    if spec_dir is None:
        config = load_project_config(project_root)
        spec_dir = config.get("spec_directory")
    if not spec_dir:
        raise BranchTestGenerationError(
            "spec_directory is not declared in jui.config.json — cannot "
            "enumerate screens (name a screen explicitly, or declare it)"
        )
    spec_path = (project_root / spec_dir).resolve()
    if not spec_path.is_dir():
        raise BranchTestGenerationError(
            f"spec directory not found: {spec_path}"
        )
    scanned: list[str] = []
    declaring: list[str] = []
    problems: list[str] = []
    for path in _spec_files(spec_path):
        screen = _screen_of(path)
        scanned.append(screen)
        try:
            with open(path, "r", encoding="utf-8") as f:
                raw = json.load(f)
        except (OSError, json.JSONDecodeError):
            # Unreadable is not "declares nothing": leaving it out of the
            # scanned list too would shrink the denominator to match the
            # numerator and report full coverage of what it could parse.
            continue
        if raw.get("type") != PARENT_SPEC_TYPE and _is_sub_spec_of_a_parent(
                path, spec_path):
            # Part of a screen, not a screen. Its parent carries it.
            continue
        spec, refusal = _load_spec_result(path)
        if refusal is not None:
            # The merger refused this parent, so `spec` is the RAW file — and
            # a raw parent carries no `branchContracts`: the block lives in the
            # sub-specs and only exists after a merge. The screen therefore
            # dropped out of `declaring` in silence, and the denominator shrank
            # by one while every remaining number stayed internally consistent.
            # Measured 2026-09-07 on a parent that declared `unitContracts`:
            # `declaring` went ['chat'] -> [], which is the reported 15 -> 14.
            #
            # A smaller denominator is the one failure this function exists to
            # prevent — it returns `scanned` precisely so "0 drifted" cannot be
            # read over a scan that reached nothing.
            problems.append(
                f"{screen}: the parent spec was refused by the merger, so its "
                f"branchContracts were NOT read — this screen has dropped out "
                f"of the count below rather than failing. {refusal}"
            )
            continue
        bc = spec.get("branchContracts")
        if isinstance(bc, dict) and bc.get("methods"):
            declaring.append(screen)
    return declaring, scanned, problems


@dataclass
class EndpointOps:
    """Declared endpoints, addressable two ways.

    ``canonical`` is keyed by the name the route will carry: the BARE method
    name while it is unambiguous, and ``<Owner>.<method>`` only for a name two
    owners declare. Keying everything qualified would have renamed the op in
    every generated file on every project that has no collision at all — the
    fix has a population, and specs without a duplicate name are not in it.
    ``aliases`` accepts the other spelling, so a contract may qualify a name
    that did not need it. A bare name two owners declare resolves to nothing
    and lands in ``collisions``.

    The flat ``name -> endpoint`` dict this replaces let the second
    declaration overwrite the first, so a spec declaring `getProfile` on two
    repositories silently bound `api.getProfile` to whichever came last and
    the other endpoint had no route at all — its screen's contract could not
    name it, and the call 599'd at run time with nothing in the spec to say
    why.
    """

    canonical: dict[str, dict]
    aliases: dict[str, str]
    collisions: dict[str, list[str]]

    def resolve(self, ref: str) -> str | None:
        """Canonical key for a reference as written, or None if unknown."""
        if ref in self.canonical:
            return ref
        return self.aliases.get(ref)


def collect_endpoint_ops(spec: dict) -> EndpointOps:
    """Declared endpoints from dataFlow repositories/useCases.

    Owner-qualified keys (`UserRepository.getProfile`) are always present;
    bare keys (`getProfile`) resolve only while they are unambiguous.
    """
    declared: list[tuple[str, str, dict]] = []
    data_flow = spec.get("dataFlow") or {}
    for section in ("repositories", "useCases"):
        for entry in data_flow.get(section, []) or []:
            if not isinstance(entry, dict):
                continue
            owner = entry.get("name")
            owner = owner if isinstance(owner, str) and owner else ""
            for method in entry.get("methods", []) or []:
                if not isinstance(method, dict):
                    continue
                name = method.get("name")
                endpoint = method.get("endpoint")
                if not (isinstance(name, str) and isinstance(endpoint, str)):
                    continue
                m = re.match(r"^([A-Z]+)\s+(\S+)$", endpoint.strip())
                if not m:
                    continue
                declared.append(
                    (owner, name, {"method": m.group(1), "path": m.group(2)})
                )

    owners_of: dict[str, list[str]] = {}
    for owner, name, _endpoint in declared:
        owners_of.setdefault(name, []).append(owner)

    canonical: dict[str, dict] = {}
    aliases: dict[str, str] = {}
    for owner, name, endpoint in declared:
        qualified = f"{owner}.{name}" if owner else name
        key = name if len(owners_of[name]) == 1 else qualified
        canonical[key] = endpoint
        if qualified != key:
            aliases[qualified] = key
    collisions = {
        name: [f"{owner}.{name}" for owner in owners]
        for name, owners in owners_of.items()
        if len(owners) > 1
    }
    return EndpointOps(canonical=canonical, aliases=aliases, collisions=collisions)


def path_to_pattern(path: str) -> str:
    """Swagger-style path -> anchored regex source ({param} -> one segment)."""
    parts = re.split(r"(\{[^}]+\})", path)
    out = ""
    for part in parts:
        if part.startswith("{") and part.endswith("}"):
            out += "[^/]+"
        else:
            out += re.escape(part)
    return f"^{out}$"


@dataclass
class MockFile:
    file: Path
    method: str
    path: str
    active_scenario: str
    scenarios: dict
    #: `source.operationId` of the GENERATED file for this route, or None.
    #: Taken from generated/ only: a hand-written overlay does not change it,
    #: because hand-written files carry operationIds of their own that need
    #: not agree with the swagger's (measured on one face: every one of them
    #: differed). An `apiOutcomeRules` side call names an operationId, and
    #: this is where it is found.
    operation_id: str | None = None


def index_mock_files(mocks_dir: Path) -> list[MockFile]:
    """One merged MockFile per route — the view `mock serve` serves.

    generated/ is read first and hand-written files overlay it per scenario
    name, the hand-written `activeScenario` winning only when explicit and
    resolvable. Returning one raw MockFile per FILE made the branch tests'
    winner a property of directory sort order once the overlay model
    guaranteed every hand-written route a generated counterpart:
    `find_mock` takes the first match, so a hand-written file sorting after
    `generated/` had its test-driven scenarios silently ignored.
    """
    from .mock.generate import GENERATED_DIR

    if not mocks_dir.is_dir():
        return []

    def _is_generated(f: Path) -> bool:
        return GENERATED_DIR in f.relative_to(mocks_dir).parts

    merged: dict = {}
    for f in sorted(mocks_dir.rglob("*.mock.json"),
                    key=lambda p: (not _is_generated(p), str(p))):
        try:
            with open(f, "r", encoding="utf-8") as fh:
                data = json.load(fh)
        except (OSError, json.JSONDecodeError):
            continue
        source = data.get("source") or {}
        method = source.get("method")
        path = source.get("path")
        scenarios = data.get("scenarios")
        if not (isinstance(method, str) and isinstance(path, str)
                and isinstance(scenarios, dict) and scenarios):
            continue
        active = data.get("activeScenario")
        explicit = isinstance(active, str) and active in scenarios
        key = (method.upper(), path)
        entry = merged.get(key)
        if entry is None:
            operation_id = source.get("operationId")
            merged[key] = MockFile(
                file=f, method=method.upper(), path=path,
                active_scenario=(active if explicit
                                 else next(iter(scenarios))),
                scenarios=dict(scenarios),
                operation_id=(operation_id
                              if _is_generated(f) and isinstance(operation_id, str)
                              else None))
            continue
        if _is_generated(f):
            # Two generated files for one route cannot happen (the tree is
            # rewritten from the swagger); if it somehow does, first wins.
            continue
        entry.scenarios.update(scenarios)
        if explicit:
            entry.active_scenario = active
        entry.file = f
    return list(merged.values())


def find_mock(mocks: list[MockFile], method: str, path: str) -> MockFile | None:
    for m in mocks:
        if m.method == method.upper() and m.path == path:
            return m
    return None


