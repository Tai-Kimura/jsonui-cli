def generate_branch_tests(
    screen: str,
    project_root: Path,
    spec_path: str | None = None,
    out_dir: str = "tests/unit/generated",
    harness_dir: str = "tests/unit/branch-harness",
    mocks_dir: str = "tests/mocks",
    platform: str = "web",
    package: str | None = None,
    module: str | None = None,
    check: bool = False,
    config_platforms: list | None = None,
    app_rules: "AppRules | None" = None,
    condition_controls: bool = False,
) -> GenerationReport:
    """Generate (or, with ``check``, compare) one screen's branch tests.

    ``config_platforms`` is `jui.config.json`'s `platforms` (None: not
    declared). A platform outside the screen's effective platforms
    (`effective_platforms`) produces nothing and expects nothing, and a file
    generated there before is retired. ``app_rules`` is the project's
    `find_app_contract_spec` result, read once by a caller generating many
    screens; None reads it here.
    """
    from .contract_declarations import (
        arranged_conditions, check_condition_uses, parse_declarations)

    spec_file = resolve_spec_path(screen, project_root, spec_path)
    if not spec_file.exists():
        raise BranchTestGenerationError(f"spec not found: {spec_file}")
    parent = _parent_of_sub_spec(spec_file, project_root)
    if parent is not None:
        # Naming a sub-spec used to fail on whatever its half of the screen
        # could not see — an endpoint declared in a sibling, most often —
        # which sends the reader to add a declaration that already exists.
        raise BranchTestGenerationError(
            f"'{screen}' is a sub-spec of '{_screen_of(parent)}', not a "
            f"screen of its own — the parent and its subSpecs are one "
            f"screen. Generate '{_screen_of(parent)}' instead."
        )
    spec = _load_spec(spec_file)

    bc = spec.get("branchContracts")
    if not isinstance(bc, dict) or not bc.get("methods"):
        raise BranchTestGenerationError(
            f"{spec_file.name} declares no branchContracts.methods — nothing to generate"
        )

    if platform not in ALL_PLATFORMS:
        raise BranchTestGenerationError(
            f"unknown platform '{platform}' — supported: web, android, ios"
        )
    if platform == "android" and not package:
        raise BranchTestGenerationError(
            "--package is required for --platform android (Kotlin package "
            "of the generated test sources)"
        )
    if platform == "ios" and not module:
        raise BranchTestGenerationError(
            "--module is required for --platform ios (the app module name "
            "for @testable import)"
        )

    # The declarations first: a malformed `alsoStatuses` or `metadata.platforms`
    # would otherwise be half-read by the steps below.
    declarations = parse_declarations(spec)
    if declarations.errors:
        raise BranchTestGenerationError(
            f"{spec_file.name}: " + "; ".join(
                f"{e.path}: {e.message}" for e in declarations.errors)
            + " (jsonui-doc validate spec reports the same)")

    # Decided BEFORE binding: a platform the screen does not exist on must not
    # fail generation over a binding error it would never have used.
    if platform not in effective_platforms(config_platforms, declarations.platforms):
        return _retire_excluded_platform(
            screen, project_root, out_dir, platform, package, check)

    if app_rules is None:
        app_rules = _app_rules_for_generation(project_root)
    # A row naming a harness condition the app does not declare (or with a
    # value outside it) is a declaration error, not a test with a guessed
    # arrangement — red-check xxviii.
    condition_errors = check_condition_uses(
        declarations.condition_uses, app_rules.conditions,
        app_rules.conditions_file.name if app_rules.conditions_file else None)
    if condition_errors:
        raise BranchTestGenerationError(
            f"{spec_file.name}: " + "; ".join(
                f"{e.path}: {e.message}" for e in condition_errors))
    mocks_path = (project_root / mocks_dir).resolve()
    mocks = index_mock_files(mocks_path)
    bindings = collect_bindings(
        spec, bc["methods"], mocks, mocks_path, platform,
        rules=app_rules.rules, declarations=declarations)
    _raise_binding_errors(bindings.errors)
    routes, rows = bindings.routes, bindings.rows
    for row in rows:
        row.conditions = arranged_conditions(app_rules.conditions, row.branch.get("when"))
    if condition_controls:
        rows = with_condition_controls(rows, app_rules.conditions)
    overlaps = [describe_overlap(a, b) for a, b in bindings.overlaps]

    if platform == "android":
        report = _emit_android(
            screen, spec, routes, rows, project_root, out_dir, harness_dir,
            package, check)
        _emit_conditions_hook(report, app_rules, project_root / harness_dir
                              / _relative_kotlin_paths(package), platform,
                              package=package, check=check)
        report.route_overlaps = overlaps
        return report
    if platform == "ios":
        report = _emit_ios(
            screen, spec, routes, rows, project_root, out_dir, harness_dir,
            module, check)
        _emit_conditions_hook(report, app_rules, project_root / harness_dir,
                              platform, module=module, check=check)
        report.route_overlaps = overlaps
        return report

    emitter = _Emitter(check)
    out_path = project_root / out_dir
    harness_path = project_root / harness_dir

    # Relative paths are computed, not walked, so the render can happen
    # before anything is dug — and a screen that turns out to belong to
    # another platform leaves no empty directory behind.
    rel = _relative_import(out_path, harness_path / screen)
    content, report = render_test_file(
        screen, spec, routes, rel, rows,
        conditions_import=_relative_import(out_path, harness_path / WEB_CONDITIONS_MODULE))
    report.route_overlaps = overlaps
    if _skip_for_platform(report):
        # The screen produced a test here until its branches moved to
        # another platform. Nothing else knows to remove it: the run that
        # stops producing a file is the only run that knows it stopped.
        emitter.retire(out_path / f"{screen}.branches.test.ts")
        emitter.apply_to(report)
        return report
    emitter.mkdir(out_path)
    emitter.mkdir(harness_path)

    runtime_file = out_path / "jsonui-branch-runtime.ts"
    emitter.emit(runtime_file, RUNTIME_TS)
    test_file = out_path / f"{screen}.branches.test.ts"
    emitter.emit(test_file, content + "\n")

    harness_file = harness_path / f"{screen}.ts"
    created = False
    if not harness_file.exists():
        # The harness is consumer-owned, so its absence is not drift and its
        # contents are never compared — but a check that stayed silent about
        # it would call a project green whose generated tests cannot compile.
        if check:
            report.harness_absent = True
        else:
            harness_file.write_text(
                # The path is RESOLVED, not a literal. The harness and the
                # runtime land in DIFFERENT directories on web
                # (`branch-harness/` beside `generated/`), and both are
                # configurable, so the fixed `./…` was the TEST file's
                # correct path copied into the harness's prose — where it
                # does not resolve. Reported by a consumer: tsc TS2307 on
                # the very import the TODO asks the reader to write.
                render_harness_skeleton(
                    screen,
                    _relative_import(harness_path,
                                     out_path / "jsonui-branch-runtime")),
                encoding="utf-8",
            )
            created = True

    report.test_file = test_file
    report.runtime_file = runtime_file
    report.harness_file = harness_file
    report.harness_created = created
    report.harness_lacks_invoke = _harness_predates_invoke(harness_file, created)
    emitter.apply_to(report)
    _emit_conditions_hook(report, app_rules, harness_path, platform, check=check)
    return report


def _harness_predates_invoke(harness_file: Path, created: bool) -> bool:
    """Does an EXISTING harness lack the `invoke` this skeleton now emits?

    Searched for as a member declaration rather than the bare word: `invoke`
    appears in prose, and a note that fires on a harness which already has
    the member is the "always wrong" line that trains its reader to skip it.

    A freshly created skeleton is never reported — it has the member by
    construction, and reporting it would make the note arrive on every first
    generation, which is the same thing as making it invisible.
    """
    if created or not harness_file.exists():
        return False
    try:
        text = harness_file.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        # Unreadable is not "has it". Saying nothing here would answer the
        # question with the reassuring value on no evidence.
        return True
    return "invoke(" not in text


def _test_file_path(screen: str, project_root: Path, out_dir: str,
                    platform: str, package: str | None) -> Path:
    """Where this screen's generated test for ``platform`` lives."""
    if platform == "android":
        return (project_root / out_dir / _relative_kotlin_paths(package or "")
                / f"{_pascal(screen)}BranchesTest.kt")
    if platform == "ios":
        return project_root / out_dir / f"{_pascal(screen)}BranchesTest.swift"
    return project_root / out_dir / f"{screen}.branches.test.ts"


def _retire_excluded_platform(
    screen: str, project_root: Path, out_dir: str, platform: str,
    package: str | None, check: bool,
) -> GenerationReport:
    """A platform outside the screen's effective platforms: nothing is
    generated, nothing is expected, and a test generated there earlier is
    retired — the run that stops producing a file is the only run that
    knows it stopped."""
    report = GenerationReport(screen=screen)
    report.platform_applicable = False
    report.platform_excluded = True
    emitter = _Emitter(check)
    emitter.retire(_test_file_path(screen, project_root, out_dir, platform, package))
    emitter.apply_to(report)
    return report


def _emit_ios(
    screen: str, spec: dict, routes: list[Route], rows: list,
    project_root: Path, out_dir: str, harness_dir: str, module: str,
    check: bool = False,
) -> GenerationReport:
    """iOS emission: Swift XCTest sources. With Xcode's file-system-
    synchronized test groups, dropping the files into the test target's
    folder is registration enough."""
    pascal = _pascal(screen)
    emitter = _Emitter(check)
    out_path = project_root / out_dir
    harness_path = project_root / harness_dir

    content, report = render_swift_test_file(screen, spec, routes, module, rows)
    if _skip_for_platform(report):
        emitter.retire(out_path / f"{pascal}BranchesTest.swift")
        emitter.apply_to(report)
        return report
    emitter.mkdir(out_path)
    emitter.mkdir(harness_path)

    runtime_file = out_path / "JsonuiBranchRuntime.swift"
    emitter.emit(runtime_file, SWIFT_RUNTIME)
    test_file = out_path / f"{pascal}BranchesTest.swift"
    emitter.emit(test_file, content)

    harness_file = harness_path / f"{pascal}BranchHarness.swift"
    created = False
    if not harness_file.exists():
        if check:
            report.harness_absent = True
        else:
            harness_file.write_text(
                SWIFT_HARNESS_SKELETON % {
                    "screen": screen, "pascal": pascal, "module": module,
                },
                encoding="utf-8",
            )
            created = True

    report.test_file = test_file
    report.runtime_file = runtime_file
    report.harness_file = harness_file
    report.harness_created = created
    emitter.apply_to(report)
    return report


