def _render_swift_branch(
    pascal: str, method_name: str, params: list[str], contract: dict,
    row: "Row", conditions: dict, *, screen: str,
) -> list[str]:
    branch = row.branch
    number = row.number
    when = branch.get("when") or {}
    then = branch.get("then") or {}
    state, seed = _arrange_state(contract, branch, conditions)
    overrides = {k[len("api."):]: v for k, v in when.items() if k.startswith("api.")}
    arg_values = {k[len("arg."):]: v for k, v in when.items() if k.startswith("arg.")}
    args = [
        _swift(arg_values.get(p)) if p in arg_values else "NSNull()"
        for p in params
    ]
    while args and args[-1] == "NSNull()":
        args.pop()
    data_refs = _collect_data_refs(then)

    name = f"test_{method_name}_branch_{number}"
    if row.also is not None:
        name += f"_also_{row.also[0]}"
    if row.control_of:
        name += "_control"

    out: list[str] = []
    out.append("")
    out.append(f"  // {_row_title(contract, row)}")
    # @MainActor: the harness factory this calls builds the real ViewModel,
    # which is MainActor-isolated in every app that builds @MainActor. The
    # class is `nonisolated` (see the class emit), so without this the body
    # cannot reach it. Harmless on a Swift 5 target and on a target whose
    # default is nonisolated — a MainActor method may call either.
    out.append(f"  {TEST_METHOD_ISOLATION} func {name}() {{")
    out.append(
        f"    runBranchTest(routes: routes, overrides: {_swift(overrides) if overrides else '[:]'},"
    )
    if row.conditions:
        # Harness conditions (design v4.11, P2d): see the Kotlin emitter.
        out.append("                      harnessFactory: {")
        for cname, cvalue in row.conditions:
            out.append(f"      arrangeCondition({_swift_str(cname)}, {_swift_str(cvalue)})")
        out.append(f"      return create{pascal}BranchHarness()")
        out.append("    }) { h, rec in")
    else:
        out.append(f"                      harnessFactory: create{pascal}BranchHarness) {{ h, rec in")
    # The act window (see the web emitter): the harness was built with the
    # protocol already serving; its construction settles, the arrangement
    # goes in, and the recorder starts counting only then.
    out.append("      h.settle()")
    if state:
        out.append(f"      h.setState({_swift(state)})")
    if seed:
        out.append(f"      seedState(h, {_swift(seed)})")
    out.append("      rec.mark()")
    for fname in data_refs:
        out.append(f"      let ref_{fname} = h.readField({_swift_str(fname)})")
    call_args = ", ".join(args)
    act_start = len(out)
    out.append(f"      h.invoke({_swift_str(method_name)}, args: [{call_args}])")
    out.append("      h.settle()")

    # See the web emitter: reach is asserted before the `then` entries so an
    # unreached route is reported as such, not as a wrong value.
    for op in _unspoken_when_ops(when, then):
        out.append(
            f"      XCTAssertGreaterThan(rec.countFor({_swift_str(op)}), 0, "
            f"\"route '{op}' declared in when was never hit "
            f"(\\(rec.countFor({_swift_str(op)})) requests)\")"
        )
    for op in _row_not_called(then):
        out.append(
            f"      XCTAssertEqual(rec.countFor({_swift_str(op)}), 0, "
            f"\"{not_called_message(op)} \\(rec.countFor({_swift_str(op)})) time(s)\")"
        )
    allowed = ", ".join(_swift_str(op) for op in row.allowed_ops)
    out.append(
        f"      XCTAssertEqual(rec.unexpectedOps([{allowed}]), [], "
        f"{_swift_str(UNEXPECTED_OPS_MESSAGE)})"
    )
    red, gate = unmatched_gate()
    if red:
        out.append(f"      XCTAssertEqual(rec.unmatchedCalls(), [], {_swift_str(unmatched_message('ios'))})")
    else:
        out.append(f"      reportUnmatched(rec.unmatchedCalls(), {_swift_str(gate) if gate else 'nil'}, "
                   f"{_swift_str(_notice_row(screen, method_name, contract, row))})")
    out.append(f"      reportUnmatchedForeign(rec.unmatchedForeign(), "
               f"{_swift_str(_notice_row(screen, method_name, contract, row))})")

    for key, value in then.items():
        if key == "api":
            out.append("      XCTAssertTrue(rec.matchedCalls().isEmpty, \"expected no declared-API calls, got \\(rec.matchedCalls())\")")
        elif key == "transition":
            out.append(f"      h.expectTransition({_swift_str(value)})")
        elif key.startswith("api.") and key.endswith(".request"):
            op = key[len("api."):-len(".request")]
            out.append(f"      XCTAssertGreaterThan(rec.countFor({_swift_str(op)}), 0)")
            out.append(
                f"      XCTAssertEqual(partialMismatches(rec.lastBodyFor({_swift_str(op)}), "
                f"{_swift_expected(value)}), [])"
            )
        elif key.startswith("api."):
            op = key[len("api."):]
            if value == "called":
                out.append(f"      XCTAssertGreaterThan(rec.countFor({_swift_str(op)}), 0)")
            # not-called: asserted before the bound (`_row_not_called`)
        elif key.startswith("data."):
            fname = key[len("data."):]
            head, *tail = fname.split(".")
            if tail:
                out.append(
                    f"      XCTAssertEqual(partialMismatches("
                    f"h.readField({_swift_str(head)}), "
                    f"{_swift_expected(_nested_expectation(tail, value))}), [])"
                )
            else:
                out.append(
                    f"      assertFieldEquals({_swift_expected(value)}, "
                    f"h.readField({_swift_str(fname)}))"
                )
    if row.control_of:
        # P2e(b): XCTAssert* records rather than throws, so the class counts
        # what is recorded while a control runs (see its `record` override).
        body = out[act_start:]
        out[act_start:] = (["      self.controlIssues = 0"] + body
                           + ["      let holds = (self.controlIssues ?? 0) == 0",
                              "      self.controlIssues = nil",
                              f"      reportConditionWithoutEffect(holds, "
                              f"{_swift_str(_notice_row(screen, method_name, contract, row))}, "
                              f"{_swift_str(_control_label(row))})"])
    out.append("    }")
    out.append("  }")
    return out


