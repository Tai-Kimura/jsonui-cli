def _unspoken_when_ops(when: dict, then: dict) -> list[str]:
    """The ops a branch ARRANGES in `when` and says nothing about in `then`.

    Declaring `when: {api.<op>: "<scenario>"}` supplies a scenario; until
    this, nothing asserted the route was ever reached. A branch could pass
    with the API never called, as long as some local failure path happened
    to satisfy the `then` data assertions — measured in the wild: an error
    branch was certifying its 409 handling against a local validation error
    (see docs/bugs/test-branch-api-scenario-branch-passes-without-the-api-
    ever-called.md). `api: "none"` could already assert zero calls; the
    positive direction had no vocabulary at all.

    `then` wins wherever it speaks. An explicit `api.<op>: "called"` already
    emits this assertion, `api.<op>: <anything else>` asserts the opposite on
    purpose, `api.<op>.request` implies reach, and the bare `api` key asserts
    no declared call happened at all. An inferred assertion must never
    contradict a written one, so all four suppress it. (No branch in the
    measured corpus declares the contradiction today — 0 of 290 — but the
    vocabulary permits it, and permitting is what decides this, not counting.)
    """
    ops = [k[len("api."):] for k in when if k.startswith("api.")]
    if not ops or "api" in then:
        return []
    spoken = {
        k[len("api."):-len(".request")] if k.endswith(".request") else k[len("api."):]
        for k in then if k.startswith("api.")
    }
    return [op for op in dict.fromkeys(ops) if op not in spoken]


def _ts(value) -> str:
    return json.dumps(value, ensure_ascii=False)


#: Prefix marking ViewModel-internal state declared in
#: `branchContracts.seedableState`. Kept in its own namespace rather than
#: mixed into the data keys because the two are written differently: data
#: keys are applied leniently (a data-only field assigned onto the VM
#: invents a property that then shadows the store), while a declared
#: internal name is asserted to land. The value may be an object or a
#: list; the read-back is then a partial match — the seed's keys only,
#: nested, lists element-wise — on web, android and ios alike.
SEED_PREFIX = "state."


def _arrange_state(
    contract: dict, branch: dict, conditions: dict
) -> tuple[dict, dict]:
    """baseline -> branch baseline -> cond witnesses -> when (later wins).

    Returns (data state, seeded internal state). Both come from the same
    three sources in the same order; only the write path differs.
    """
    state: dict = {}
    seed: dict = {}

    def absorb(source: dict) -> None:
        for key, value in source.items():
            if key.startswith(SEED_PREFIX):
                seed[key[len(SEED_PREFIX):]] = value
            else:
                state[key] = value

    baseline = contract.get("baseline")
    if isinstance(baseline, dict):
        absorb(baseline)
    # The branch's own pre-state, over the method's, KEY BY KEY — the whole
    # value of every key it names, never a merge into one.
    #
    # A deep merge would rebuild the defect this exists to remove. The
    # method's baseline could hold a list and the branch could reach inside
    # it, so a branch would again be able to move part of a state and leave
    # the rest agreeing with the old one — which is how a list with a row in
    # it ended up beside an "the list is empty" flag, arranged and asserted
    # against a state the implementation cannot produce. Owning the key
    # outright is what makes the resulting state readable in one place.
    branch_baseline = branch.get("baseline")
    if isinstance(branch_baseline, dict):
        absorb(branch_baseline)
    when = branch.get("when") or {}
    cond_ref = when.get("cond")
    if isinstance(cond_ref, str) and cond_ref:
        negated = cond_ref.startswith("!")
        name = cond_ref[1:] if negated else cond_ref
        cond = conditions.get(name) or {}
        witness = cond.get("witness_false" if negated else "witness_true")
        if not isinstance(witness, dict):
            raise BranchTestGenerationError(
                f"condition '{name}' has no "
                f"{'witness_false' if negated else 'witness_true'} — test "
                "generation needs a witness to arrange the state"
            )
        absorb(witness)
    for key, value in when.items():
        if key.startswith("data."):
            state[key[len("data."):]] = value
        elif key.startswith(SEED_PREFIX):
            seed[key[len(SEED_PREFIX):]] = value
    return state, seed


def _branch_title(index: int, branch: dict) -> str:
    when = branch.get("when") or {}
    parts = []
    for key, value in when.items():
        parts.append(f"{key}={json.dumps(value, ensure_ascii=False)}")
    return f"branch {index}: " + (" & ".join(parts) if parts else "(empty when)")


#: Said when a test records a call its method's rows do not reach. The bound
#: is what keeps "delete the row that reaches an endpoint" from being the
#: cheapest way to make its uncovered statuses disappear.
#:
#: 🔻 AND IT SAYS HOW FAR "called" REACHES. The bound is per method: one row
#: writing `api.<op>: "called"` allows the op in every row of that method that
#: does not mention it. Said only as "say so in a row", the fix for one red
#: row silently allowed the call in the rows where it must not happen (a
#: consumer's save method: its error rows stopped refusing the refetch). The
#: distinction is visible only at the moment a red is cleared, so this
#: message — the thing read at that moment — says it (design v4.9, red-check
#: xxv). One constant: the three renderers print it escaped.
UNEXPECTED_OPS_MESSAGE = (
    "declared routes called outside what this method's rows reach — if the "
    "method makes the call, say so in the row whose act makes it (then "
    "api.<op>: \"called\"); that allows <op> in every row of this method "
    "that does not mention it, so a row that must not make the call says "
    "api.<op>: \"not-called\". If the app's network layer makes it, admit it "
    "with apiOutcomeRules")


#: P2e(a) (design v4.14): a request in the act window that no declared route
#: answered got the runtime's 599 — a response no server returns — so what the
#: view model did next is made up (#28). From the release this literal names,
#: every generated test fails on one; before it, the test prints a warning per
#: request instead, and that warning is the notice. No default (the same rule
#: as validate's coverage gate, v4.13): a version derived from the running one
#: agrees with itself on every build and would never switch the red on. Set it
#: when the release that announces the red is cut; unset, the warning promises
#: no release.
UNMATCHED_GATE_FROM: str | None = None

UNMATCHED_MESSAGE = (
    "requests in the act window reached no declared route — the runtime "
    "answered them with a 599 no server returns, so what the view model did "
    "next is made up. Declare the route and its scenarios (dataFlow + mock); "
    "a call the app's network layer makes around every request is admitted "
    "once, with apiOutcomeRules sideCalls")

#: Only requests to the app's own API fail (design v4.19): another host is
#: the info `unmatched_foreign`. A face that cannot tell the two apart counts
#: the request as the app's, and the message says how to tell them apart.
#: Android needs none: MockWebServer records only its own host:port.
UNMATCHED_CLASSIFY = {
    "web": (" If a host named here is not the app's API, export `apiOrigins` from the "
            "harness (the app's API origins, e.g. [\"https://api.example.com\"]): "
            "requests to other hosts then become the info unmatched_foreign"),
    "ios": (" If a host named here is not the app's API, give the harness `apiOrigin` "
            "(the app's API base URL): requests to other hosts then become the info "
            "unmatched_foreign"),
    "android": "",
}


def unmatched_message(platform: str) -> str:
    return UNMATCHED_MESSAGE + "." + UNMATCHED_CLASSIFY.get(platform, "")


